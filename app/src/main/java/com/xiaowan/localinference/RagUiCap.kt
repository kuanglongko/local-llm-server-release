package com.xiaowan.localinference

/**
 * 「一屏最多画多少」的**纯逻辑**（零依赖：不 import 任何东西，连 `org.json` 都不用）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么单独立一个文件、且必须是纯逻辑
 * ══════════════════════════════════════════════════════════════════════════
 * 知识库页有**两个**会把"库里有几条"直接铺成 View 的地方：
 *
 *   · [EngineActivity.renderRagRows] —— 逐条列表（每行 = LinearLayout + TextView
 *     + Button，三个 View）；
 *   · [EngineActivity.renderRagList] —— 库列表（每个库一个 TextView）。
 *
 * 两个都长在**外层那个 `rootScroll`（ScrollView）**里 —— 它**不做**任何虚拟化：
 * 丢进去 N 个子 View，measure/layout 就实打实做 N 次，全在一帧里、全在主线程上。
 *
 * 用户报的现场是 7021 条的一个库（他自己切出来的），那一屏要铺
 * `7021 × 3 ≈ 21000` 个 View，外加把 6 MB 正文 `setText` 进 EditText。
 * 结果就是"进了向量页直接卡、页面空白、连正常的库都看不到"—— 那不是渲染慢，
 * 是**一帧要干的活超过了帧预算好几个数量级**，而后面排着的东西（库列表、
 * 状态行、按钮）一个都画不出来。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么"截断"在这里是对的，而在别处几乎都是错的
 * ══════════════════════════════════════════════════════════════════════════
 * 本仓库对"静默截断"的判据一向很硬（见 [RagArchive.MAX_TEXT_CHARS]、
 * [RagIndexStore.ChunkParams.maxChunks]）：截了不说 = 用户以为文件里就这么多。
 * 但这一处截的**不是数据**，是"**一次画多少个**"：
 *
 *   · 数据一个字节都没少 —— 还在 `texts.jsonl` 里、还在编辑器里（受
 *     [MAX_DOC_CHARS] 那一档保护，它有明确的说明）、条目仍然能被检索命中；
 *   · 被截的是"这一屏的行"，而用户在这一屏要做的事（找到某一条、删掉它）
 *     在几千条的规模下**本来就靠不了肉眼**；
 *   · 所以它必须**出声**：[rowsPageNote] 说清"这一页 N 条、还有 M 条在别的页上"。
 *
 * 判据因此落在"**说了没有**"，而不是"截了没有"—— 一个不说话的截断在这里
 * 与在别处一样坏。
 *
 * ⚠ 数字只在这一个文件里出现：`renderRagRows` 与 `renderRagList` 两处各写一个
 *   （哪怕是同一个数），改一处另一处不会红 —— 本仓库对"同一条规则两份实体"
 *   的判据正是冲着这个来的（见 PR #264 收口切分表那件事）。
 */
object RagUiCap {

    /**
     * 条目列表**一屏最多铺多少行**。
     *
     * 为什么是 60：每行三个 View，60 行 = 180 个 View —— measure/layout 一次
     * 稳定落在 1 ms 量级，即在最差的机器上也离 16.7 ms 的帧预算很远。
     *
     * ⚠ 这个数从 300 降到 60 是**可逆**的，因为分页（[rowPageCount] /
     *   [rowPageRange]）同时进来了：以前 300 是"你能看到的全部"，降到 60
     *   就意味着 694 条要重导一次才能摸到；现在 60 只是"一页有多少"，
     *   第 7000 条点几下就能翻到。**上限与可达性是两件事** —— 前者是性能
     *   闸门，后者是功能。把两者压在同一个数上，才会出现"降它 = 砍功能"
     *   这个假的取舍。
     *
     * 为什么**不**再往下（比如 20）：一页太小会反过来伤"相邻条目一起看"这件事
     *   （同一次追加的几条、同一段被切开的几块，往往要挨着看），而且翻页本身
     *   要一次点击。60 是这个取舍上的一个平衡点，不是算出来的最优解。
     */
    const val MAX_ROWS = 60

    /**
     * 正文编辑器**单次回填**的字符上限 —— 从 40 万字符降到 4 万。
     *
     * 为什么降：`EditText.setText` 的代价是**给整段文本做一次全量布局**，
     * 与"屏幕上看得见多少"无关。40 万字符在低端机上是几百毫秒，4 万字符是
     * 几十毫秒 —— 而这一档真正的意义不在那几百毫秒，在它**之后**：光标移动、
     * 每次 `TextWatcher`、以及用户在这个框里敲一个字，都要在这份布局上重算。
     *
     * 4 万字符 ≈ 88 条（按每条约 450 字算）。它比 [MAX_ROWS] × 450 = 27000
     * 略大 —— 是**故意**的：一页的条目全装进框里，才谈得上"看着列表改正文"。
     * 两档互相咬合（见 [docCharsForRows]），不是两个随手定的数。
     *
     * ⚠ 与 [RagArchive.MAX_TEXT_CHARS]（10 万）**不是**同一件事，别合并：
     *   · `MAX_TEXT_CHARS` 是**一条正文**的硬顶（超了截断并计数）；
     *   · 这一档是**整个编辑器一次装多少**。
     */
    const val MAX_DOC_CHARS = 40_000

    /**
     * 正文框**收起**之后还剩几行。
     *
     * ══════════════════════════════════════════════════════════════════════
     * 为什么"收起"这件事必须存在，而不是把上限继续往下调
     * ══════════════════════════════════════════════════════════════════════
     * [MAX_DOC_CHARS] 是"**能装多少**"，不是"**屏幕上占多高**"。这两件事在
     * `EditText` 上被绑在一起：`WRAP_CONTENT` 的框有多少内容就多高，4 万字符
     * （≈ 88 条、几百行）在这一页上就是**十几屏**。
     *
     * 而这一页里排在框**下面**的东西，恰好是用户最常要去的地方：
     *   · 「追加」那一行（补一条笔记）；
     *   · 条目列表（按条查看 / 删某一条）。
     * 于是"往下滚"成了每次都要付的通行费 —— 用户报的原话：
     * *"有的时候滑倒底部去追加或者按条查看，滑动太慢"*。
     *
     * ⚠ 调 [MAX_DOC_CHARS] **解决不了**它：那个数说的是"能装多少内容"，
     *   调到多小都是在"装不下"与"占得高"之间换 —— 而用户此刻的内容确实要装进去。
     *   真正要的是把**内容**与**屏幕占用**解耦：内容一份不少，占的高度由用户选。
     *   所以这里给的是一个**开关**（[EngineActivity] 里的折叠按钮），不是一个新上限。
     *
     * 为什么是 3：正好等于 [EngineActivity.ragDocEt] 的 `minLines`，也就是
     * **这一行控件本来就会占的高度**。收起之后框不会比"它本来最小该占的地方"更矮
     * —— 再低会让它看起来像一个被压扁的、看不出有内容的空条，而"框里还有东西"
     * 这件事必须在收起状态下**仍然看得见**（否则与"这份内容没了"长得一样）。
     */
    const val DOC_COLLAPSED_LINES = 3

    /**
     * 正文框那个「收起 / 展开」按钮上的字（`collapsed` = 现在是不是收起态）。
     *
     * ══════════════════════════════════════════════════════════════════════
     * 为什么这句话要报**字符数**，而不只是"收起/展开"四个字
     * ══════════════════════════════════════════════════════════════════════
     * 收起之后，框里那份内容在屏幕上只剩 3 行 —— 而**"收起"与"内容被弄丢了"
     * 在前两秒是完全一样的**。本仓库对这种"静默变少"的判据一向是硬的
     * （见 [docTruncatedOnDiskNote] 那一族），而这里解锁它的信息只有一处：
     * 按钮上这个数。它在收起态也必须说着同一份内容有多少 —— 于是用户能看出
     * "只是收起来了，不是没了"，而不是去重导（导入是追加合并，重导条目翻倍）。
     *
     * ⚠ 被截过（[docTruncatedOnDiskNote] / [docTruncatedSoleCopyNote] 那一档）
     *   时按钮上要**带上那个旗标**：框里那份的说明写在正文**末尾**，收起之后
     *   正好看不到 —— 而"框里不是全部"这件事恰恰是最不能靠翻找才发现的一条。
     *   所以它必须出现在**收起态也看得见的那一行**上。
     *
     * @param chars 框里**实际装着**多少字符（不是全文长度 —— 那是另一个数）
     * @param clipped 框里这份是不是被截过的头部
     */
    fun docToggleLabel(collapsed: Boolean, chars: Int, clipped: Boolean): String {
        val head = if (collapsed) "▶ 展开正文框" else "▼ 收起正文框"
        val size = if (chars <= 0) "空" else "$chars 字符"
        val tail = if (clipped) "，只是前一部分" else ""
        return "$head（$size$tail）"
    }

    /**
     * 收起态下、正文框**位置**上的那一行说明（`null` = 展开态不必说）。
     *
     * 为什么收起之后**还要**留一行字：一个 3 行的框（[DOC_COLLAPSED_LINES]）
     * 与一个"内容很短"的框长得一模一样，而两者的下一步完全不同 ——
     * 前者要展开才看得全，后者本来就是全部。一行字把这件事分开，
     * 且它必须**说清收起只是显示**（内容没动、下面那些按钮照常按）。
     */
    fun docCollapsedNote(chars: Int, clipped: Boolean): String? {
        if (chars <= 0) return null
        return if (clipped)
            "正文框已收起（里面是前一部分内容）—— 展开可看，内容没有被改动"
        else
            "正文框已收起 —— 展开可看，内容没有被改动"
    }

    /**
     * 库列表**一屏最多画多少个库**。
     *
     * 与 [MAX_ROWS] 不同档：一个库只有一个 TextView，便宜得多；而"我有哪些库"
     * 是**全局**判断，比"某一条在第几行"更需要看全。1000 个库 ≈ 1000 个
     * TextView，是这一屏还撑得住的上限。
     */
    const val MAX_LIBS = 1000

    /**
     * 条目列表分页之后的那句"这只是一页"（`null` = 只有一页，不必说）。
     *
     * 它是条目列表**唯一**的那句说明。曾经这里用的是另一句
     * "只显示了**前** N 条" —— 分页之后那是**错的**（显示的可能是第 3 页的
     * 第 121–180 条），而"前"这个字会把用户引向"继续往下滑"：
     * 列表到底了就是到底了，剩下的在**别的页**上。
     *
     * 措辞刻意不用"未显示"三个字就完事：光说"还有 6940 条未显示"会读成
     * "看不见了"，而这里的真相是"翻页就能看到"。所以句子必须带上**动作**
     * （「用上面的『下一页』翻」），并把"一条都没少"这一层保住 ——
     * 否则用户会以为要重导，而导入是追加合并，重导等于条目翻倍。
     */
    fun rowsPageNote(shown: Int, total: Int): String? {
        if (total <= shown) return null
        return "… 这一页显示了 $shown 条，另有 ${total - shown} 条在「下一页」那几页上" +
            "（数据一条都没少，仍可检索/导出）"
    }

    /**
     * 库列表的截断说明。与 [rowsPageNote] 分开是因为"库"与"条"是两个单位
     * —— 共用一句话会让"还有 3 个未显示"读成"还有 3 条"。
     *
     * ⚠ 库列表**不做分页**（与条目列表不同档）：一个库只有一个 TextView，
     *   1000 个也才 1000 个；而"我有哪些库"是全局判断，比"某一条在第几行"
     *   更需要看全。所以这里截了就是真的"没显示"，措辞与分页那句**必须不同** ——
     *   说成"在别的页上"而其实翻不到，比不说更坏。
     */
    fun moreLibsLabel(shown: Int, total: Int): String? {
        if (total <= shown) return null
        return "… 只显示了前 $shown 个库，另有 ${total - shown} 个未显示" +
            "（都在磁盘上，导出时不受影响）"
    }

    /**
     * 正文框被截断时的说明 —— **磁盘上有这份内容的完整副本**（`null` = 没截）。
     *
     * ══════════════════════════════════════════════════════════════════════
     * 为什么这一句必须拆成**两条**，不能一句通用
     * ══════════════════════════════════════════════════════════════════════
     * 正文框被截的那条路有**两个来源**，而它们的下一步**刚好相反**：
     *
     *   · [EngineActivity.loadRagDoc] —— 框里这份是**某个库**的正文的头部，
     *     那个库的完整正文就在磁盘上（`texts.jsonl`）。这里"磁盘上那份是完整的"
     *     是**真的**，"点「建索引/重建索引」选「用磁盘上那份」"走得通；
     *   · [EngineActivity.applyRagTextImport] —— 框里这份是**刚导入的纯文本**的头部，
     *     这条路**还没有落盘**。磁盘上没有任何地方有这份内容的完整副本 ——
     *     而"用磁盘上那份"要么没有入口，要么更坏：**去读了另一个库的正文**。
     *
     * 上一轮这两条路共用一句，于是"磁盘上那份是完整的"印在了**第二条**路上 ——
     * 那是一句**假话**，而且它正好把人引到一条死路：用户按那句提示点了
     * 「用磁盘上那份建索引」，App 读的是**当前那个小库**的 `texts.jsonl`（不是他
     * 刚导进来的 3 MB），建完回执还写「索引已重建」—— 三兆正文一个字节都没进去，
     * 而屏幕上的每一个字都在说"成了"。（用户报的原文：「选择用磁盘上那份建索引，
     * 点击后并没有效果，直接提示索引已重建，查看私有文件夹内，jsonl 文件实际
     * 只是刚建小库的数据，文本完全没导入」。）
     *
     * 所以这里**不**给一个 `diskBacked: Boolean` 开关：开关的默认值总有一半是错的，
     * 而两个分支的文案除了"报数"以外**没有一句共用**。两条独立函数让调用处
     * 必须自己选，选错在代码里看得出来（函数名相反），而不是靠传一个 `true`/`false`。
     *
     * 必须同时说清**三件事**，缺一个用户就会得出错的结论：
     *   ① 框里只装了一部分（不然他会以为库就这么大）；
     *   ② **磁盘上那份是完整的、且没有被改动**（不然他会以为内容被弄丢了，
     *      去重导 —— 而导入是追加合并，重导会让条目翻倍）；
     *   ③ 想用完整那份怎么办（点「建索引/重建索引」时选"用磁盘上那份"）——
     *      给出**可执行的**下一步，而不是让他自己猜。
     */
    fun docTruncatedOnDiskNote(shownChars: Int, totalChars: Int): String {
        return "…（正文框只装了前 $shownChars 字符 —— 全文共 $totalChars 字符，太多放不进" +
            "这一个框。磁盘上那份是完整的，没有被改动：点「建索引/重建索引」时选" +
            "「用磁盘上那份建索引」即可；要改全文请分小库维护，" +
            "要在库里补一条请用「追加」）"
    }

    /**
     * 正文框被截断时的说明 —— 框里这份是**唯一的副本**（`null` = 没截）。
     *
     * 与 [docTruncatedOnDiskNote] 是**相反的真相**，所以措辞里**不许**出现
     * "磁盘上那份"五个字：这里磁盘上**没有**这份内容（纯文本导入这条路还没落盘），
     * 说它有，用户就会去找一个不存在的东西，或者被引到"读另一个库的正文"上去。
     *
     * 也不能只说"框里只装了前 N 字符"就完事 —— 那句话挡住的是"他以为库就这么大"，
     * 挡不住真正会毁内容的那件事：用户会**以为这份完整的文档已经被导进来了**，
     * 然后去点「建索引/重建索引」。所以这里要显式说清"磁盘上还没有"，
     * 并给两条**真的走得通**的路（切小文件分库导入 / 先建小库再用「追加」逐条补）。
     *
     * ⚠ 这**不是**一句"警告噪音"：它只在超限时出现（[RagUiCap.MAX_DOC_CHARS]
     *   以下一个字都不说），而出现的那一刻用户手上没有任何别的线索能告诉他
     *   "后面那 90% 现在只在这个框里、且这个框只装了头部"。
     *
     * ══════════════════════════════════════════════════════════════════════
     * ⚠ `0.9.198` 起：这一版**没有调用方了** —— 而且这是对的
     * ══════════════════════════════════════════════════════════════════════
     * 唯一会让"框里是唯一副本"成立的那条路（`.txt / .md` 导入**不落盘**、
     * 只把头部填进框）已经在 `0.9.198` 改成"解析完直接落库、由 [loadRagDoc]
     * 回读" —— 而 [loadRagDoc] 读的就是磁盘上那个库的 `texts.jsonl`。
     * 于是"框被截"这件事现在**只发生在磁盘上有完整副本**的那条路上，
     * 这一版说明在今天的调用图里**不可达**。
     *
     * 那为什么不删掉它：
     *   · 它是**一条真相**，不是一个分支。删掉它，"磁盘上有没有这份内容"
     *     这个分水岭就从源码里消失了 —— 而下一个人只要再加一条"不落盘的导入"
     *     （粘贴一篇、从剪贴板读、云文档……），就必须**重新踩一遍**上一轮那个坑：
     *     两句真相共用一句，于是假话被印在它不成立的那条路上，
     *     而用户照着那句假话点下去，索引的是**另一个库**、回执还说"成了"；
     *   · 本文件是零依赖纯逻辑，留一个字符串函数不占任何运行时成本。
     *
     * ⚠ 但**不许**为了"别让它是死代码"而随便给它找个调用方：它成立的唯一前提是
     *   "磁盘上没有任何地方存着这份内容的完整副本"。当前没有任何一条路满足它 ——
     *   谁要调它，先证明那个前提（`tools/run_rag_doc_fold_guard.sh` 与
     *   `tools/rag_ui_cap/check_wiring.py` 都正面钉着这两句**互不串门**）。
     */
    fun docTruncatedSoleCopyNote(shownChars: Int, totalChars: Int): String {
        return "…（正文框只装了前 $shownChars 字符 —— 全文共 $totalChars 字符，" +
            "太多放不进这一个框。⚠ 这份内容还没有写进任何库：" +
            "磁盘上没有它的完整副本，框里这一份就是唯一的。所以这一步不能直接点" +
            "「建索引/重建索引」（那只会索引到这个头部）。请把文档切成更小的文件、分成几个库导入；" +
            "或者先建一个小库，再用「追加」逐条补）"
    }

    /**
     * 把一段文本按 [MAX_DOC_CHARS] 截到**字符边界**上（绝不切在代理对中间）。
     *
     * ⚠ 复用 [TextBoundary.clipAtCharBoundary]，**不**在这里再写一份边界判断：
     *   那个坑（`(c.code and 0xC0) == 0x80` 那条按字节的判据会把正常汉字误判）
     *   本仓库真踩过，两份实体就是"改一处另一处不红"。
     *
     * @return 截好的文本；没超限时**原样返回同一个对象**（不复制大字符串）。
     */
    fun clipDoc(s: String): String =
        if (s.length <= MAX_DOC_CHARS) s else TextBoundary.clipAtCharBoundary(s, MAX_DOC_CHARS)

    // ══════════════════════════════════════════════════════════════════════════
    // 分页：把 [MAX_ROWS] 从"你能看到的全部"变回"一页有多少"
    // ══════════════════════════════════════════════════════════════════════════
    // 为什么必须有这一块，而不是把 [MAX_ROWS] 简单调大调小：
    //
    //   用户的原话是"窗口太小，滑动找 300 条、40 万字，也是一场灾难"。
    //   那两句抱怨指向的是**同一个东西**：一屏铺 N 行，N 越大越卡、越难翻；
    //   N 越小，能找到的范围越小。**只要"铺多少"就是"能看到多少"，
    //   这个取舍就没有解** —— 把 N 从 300 降到 60，只是从"卡且难找"
    //   换成"不卡但更找不到"。
    //
    //   分页把这个耦合拆开：一页铺 [MAX_ROWS] 行（性能闸门），而
    //   [rowPageCount] 页覆盖全部条目（可达性）。于是上限可以放心地小，
    //   而每一条仍然摸得到 —— 这是"降低上限"这个动作**终于成立**的前提。
    //
    // ⚠ 这里只做**算术**：页从哪到哪、有没有上/下一页。按钮、文案、点击
    //   一律留在 UI 层 —— 纯逻辑不该知道 Android 的存在，否则它就没法被
    //   离线单测钉住，而这正是它存在的理由。

    /**
     * 一共要几页（`total` = 条目总数）。
     *
     * `total <= 0` 时返回 **0**，不是 1：一个空库**没有**第 1 页可以翻。
     * 返回 1 会让"翻页条"在一个空库上也画出来，而它点什么都没用 ——
     * 那种"看起来能用但用不了"的控件是本仓库反复收口的东西。
     */
    fun rowPageCount(total: Int): Int {
        if (total <= 0) return 0
        return (total + MAX_ROWS - 1) / MAX_ROWS
    }

    /**
     * 第 `page` 页在条目表上的**半开区间** `[from, to)` —— 直接给
     * `subList(from, to)` 用，省掉调用处再算一次起止（两处各算一次必然漂移）。
     *
     * 越界一律**钳制**而不是抛异常：
     *   · `page < 1` -> 按第 1 页（用户删条目删到当前页没了时，最自然的落点）；
     *   · 超出末页 -> 按末页（同上；在这里抛异常会把"删到最后一条"变成崩溃）。
     *
     * ⚠ 钳制的方向是"回到还有内容的页"，**不是**"夹到 0"：夹到 0 会让
     *   末页上的用户看到一张空列表，而磁盘上明明还有内容 —— 那与"我的库空了"
     *   长得一样（本仓库对这种"静默变空"的判据一向是红的）。
     */
    fun rowPageRange(total: Int, page: Int): IntRange {
        if (total <= 0) return IntRange.EMPTY
        val pages = rowPageCount(total)
        val p = page.coerceIn(1, pages)
        val from = (p - 1) * MAX_ROWS
        val to = minOf(from + MAX_ROWS, total)
        return from until to
    }

    /**
     * 翻页条的文案（`null` = **只有一页，不必画翻页条**）。
     *
     * 为什么只有一页时不画：几十条的库是常态，那时"第 1/1 页"是纯噪音，
     * 而噪音会让真出现多页时的那一行也被无视（本仓库对警告噪音的一贯判据）。
     *
     * ⚠ 文案里**同时**要出现"第几页/共几页"与"这一页是哪几条"：
     *   只看"第 3/118 页"用户不知道自己在文件的哪一段，只看"第 121–180 条"
     *   又不知道还剩多少。两个都要给。
     */
    fun pageLabel(total: Int, page: Int): String? {
        if (rowPageCount(total) <= 1) return null
        val pages = rowPageCount(total)
        val p = page.coerceIn(1, pages)
        val r = rowPageRange(total, p)
        return "第 ${r.first + 1}–${r.last + 1} 条 · 第 $p/$pages 页"
    }

    /**
     * 一页最多有多少行 —— 也就是"分页之后，条目列表还要不要截"。
     *
     * 它恒等于 [MAX_ROWS]，留着这个名字是为了让调用处的意图读得出来
     * （"这是分页的页大小"，不是"又一次截断"），也因为**它必须与
     * [rowPageRange] 用的是同一个数**：两处各写一个 `MAX_ROWS`，
     * 改一处另一处不会红。
     */
    // ══════════════════════════════════════════════════════════════════════════
    //  删除一条之后：**本地**把那张「行号 -> 摘要」表改对
    // ══════════════════════════════════════════════════════════════════════════

    /**
     * 「正文文件里的第 `index` 行刚被删掉」之后，把条目表**本地**改对
     * （`null` = 这一次推算不能信，调用方应退回重读磁盘）。
     *
     * ══════════════════════════════════════════════════════════════════════════
     * 为什么这是一条**纯函数**
     * ══════════════════════════════════════════════════════════════════════════
     * `RagIndexStore.removeEntry` 做的是一件**完全确定**的事：把 `lines[index]`
     * 拿掉、其后每一行前移一位、重写正文与向量。于是"删完之后磁盘上是哪张表"
     * 根本不需要读盘 —— 它就是"把本地这张表按下标 `index` 摘掉一格"。
     * 而重读一次是拿 6 MB 的 `texts.jsonl` 换一个**已知**的答案，这段时间里
     * 主线程排在后面的操作一个都动不了（这一族 bug 的第一形态就是"点了没反应"）。
     *
     * ⚠ 但这条推算只在**本地那份与磁盘逐行一致**时才成立，所以：
     *   · 表必须是"下标即行号"的（`rows[i].first == i`）—— 那是 UI 侧用
     *     `readEntriesAligned` 建表时就钉住的。**错位的话"删错隔壁那一行"
     *     那个老缺陷就借这次优化回来了**，而它不崩不报错、屏幕上一切正常；
     *   · 对不上一律返回 `null` -> 调用方退回重读。宁可慢一次，
     *     绝不按一份来路不明的表推算行号。
     *
     * ⚠ 行号按**新位置**重建（`0,1,2,…`），不是"把那一格留个洞"：删除的语义
     *   就是"其后每一行前移一位"，留着旧行号会让后面每一行都指向**上一条**
     *   —— 而屏幕上显示的标号与点「删」传出去的行号就此分家。
     */
    fun dropRowAt(rows: List<Pair<Int, String?>>, index: Int): List<Pair<Int, String?>>? {
        if (rows.isEmpty() || index < 0 || index >= rows.size) return null
        // 不变量：下标即行号。对不上 = 这份表来路不明，不许按下标推算。
        for (i in rows.indices) if (rows[i].first != i) return null
        val kept = ArrayList<Pair<Int, String?>>(rows.size - 1)
        for (i in rows.indices) if (i != index) kept.add(rows[i])
        // 行号 = 新位置（删除是"前移"，不是"留洞"）。
        val out = ArrayList<Pair<Int, String?>>(kept.size)
        for (i in kept.indices) out.add(i to kept[i].second)
        return out
    }

    const val ROWS_PER_PAGE = MAX_ROWS

    /**
     * 给定"一页行数"，正文框至少要能装下多少字符 —— 用来把
     * [MAX_DOC_CHARS] 与 [MAX_ROWS] **咬合**起来，而不是两个随手定的数。
     *
     * 为什么"一页的条目全进正文框"是硬要求：用户在这一屏做的两件事
     * （看列表找一条、在框里改它）必须落在**同一份数据**上。框里只装了
     * 前 88 条而列表显示前 60 条，此时"第 50 条的删"与"框里第 50 行"
     * 还勉强对得上，等翻到第 2 页就完全对不上了 —— 而**错位的删除不崩不报错**
     * （本仓库那个"删错行"的老缺陷就是这么来的）。
     *
     * 所以：`MAX_DOC_CHARS >= 一页行数 × 单条字数`，那个 450 是本仓库
     * 反复出现的"一条正文"的典型长度（≈ [RagArchive.EMBED_MAX_CHARS] 448）。
     */
    fun docCharsForRows(rows: Int): Int = rows * 450

    /**
     * 正文框装得下"一页条目"吗？给守卫用的一条**关系判据**。
     *
     * 单独抽成函数而不是在测试里写死一个数：关系本身是要求，
     * 数值是它的实现 —— 改 [MAX_ROWS] 时这条会跟着走，而写死的数不会。
     */
    fun docWideEnoughForRows(): Boolean = MAX_DOC_CHARS >= docCharsForRows(ROWS_PER_PAGE)

    // ══════════════════════════════════════════════════════════════════════════
    // P1-a：正文框从「编辑器」改成「只读预览一片」（ISSUE #228）
    // ══════════════════════════════════════════════════════════════════════════
    // 上面那一族（[MAX_DOC_CHARS] / clipDoc）修的是"**一次回填多贵**"：把 6 MB
    // 截到 4 万字符，让 `setText` 的全量布局从十秒级降到几十毫秒。但那是**收费的**
    // —— 上限只挡住了最坏的一档，库再大一点、9 万字符，同样一个 `setText` 又回到
    // 秒级，而用户看到的是同一件事：点开库，等。
    //
    // 根不在"截得够不够狠"，在**这个框一次要装多少**。P1-a 就动这一处：
    // 框不再装"整个库"，只装**当前这一页**（与条目列表同一页、同一段行号），
    // 而且**只读** —— 编辑改走下面那两行已经存在的路（「追加」一条 / 每条一个「删」）。
    //
    // ⚠ 为什么"只读"是**必须**的，而不是顺手加的：这个框一旦能编辑，
    //   [EngineActivity.ragDocEntries]（"把框里的内容当成要索引的全部"）就永远是
    //   一句话说两件事的判据 —— 而 P1-a 之后框里**只有一页**，
    //   拿它去「建库/重建」或「保存正文」会**静默地**把整个库换成那一页
    //   （保存那一条更狠：`texts.jsonl` 被整份覆盖）。所以"框只读"与
    //   "取正文不再走框"这两件事必须一起做，判据也钉在这一对上（见
    //   `run_rag_doc_preview_guard.sh`）。

    /**
     * 正文框**是不是这一片的只读预览**（`false` = 它仍是可编辑的输入框）。
     *
     * ══════════════════════════════════════════════════════════════════════
     * 为什么这里仍留了一个 `false`，而不是"框永远只读"
     * ══════════════════════════════════════════════════════════════════════
     * `false` 只对一种库成立：**新建的、磁盘上还没有它的**那个库（[ragPendingKb]）。
     * 它的内容是用户刚粘进来 / 敲进去的，而磁盘上**没有任何副本**可以拿来做预览 ——
     * 此时框不是"某个库的窗口"，它**就是**那份内容本身。把它也设成只读，
     * 等于把这个入口整个关掉（ISSUE #259 用户要的"粘贴后立即保存"就没有路了）。
     *
     * 判据因此是**状态**而不是"哪个库"：只要那个库在磁盘上有一个目录，
     * 框就必须是预览（预览的是磁盘那份的第 k 页），编辑一律走追加/删除。
     * 反过来，用户往框里敲第一笔之后，pending 就落盘了（[EngineActivity.autosavePendingKb]）,
     * 于是这个 `false` 是**短暂的**、且它结束的那一刻磁盘上已经有一份了。
     *
     * @param pendingNotLanded 这个库是不是"新建、还没落盘"的那一个
     */
    fun docIsSlice(pendingNotLanded: Boolean): Boolean = !pendingNotLanded

    /**
     * 这一片正文的**取字符范围**：与条目列表**同一页**（[rowPageRange]）。
     *
     * 为什么预览的是"一页"而不是"头 4 万字符"（[clipDoc] 那一版）：
     * 头 4 万字符这个切法把框和列表**解耦**了 —— 列表翻到第 3 页时，
     * 框里还停在前 88 条上。用户在两个界面之间读同一件事，得到的却是两份
     * 不同的行 —— 而 P1-b 之后"改的是哪一段"靠的就是"框与列表说的是同一段"。
     * 同一页是唯一能让"我在看第 121–180 条"在两个控件里**同时为真**的切法。
     *
     * 返回的区间直接给 `subList` 用；越界由 [rowPageRange] 钳制（不抛异常）。
     */
    fun docPreviewRange(total: Int, page: Int): IntRange = rowPageRange(total, page)

    /**
     * 框里那一片的正文怎么拼（`null` = 空库 / 没有行）。
     *
     * 与 [EngineActivity.ragDocEntries] 的拼法**刻意不同**：那一版 `filter` 掉了
     * 空行、`trim` 了每一条（它是"要索引的条目表"）；这一版是**给人看的预览** ——
     * 行号必须与条目列表**逐行对齐**（`null` = 这一行读不出来，保留一个占位行），
     * 否则"列表第 5 条"与"预览第 5 行"又会分家，而那个正是删错行那族的老缺陷。
     *
     * @param rows 这一页的行（来自 `readEntriesAligned`，下标即行号）
     */
    fun docPreviewText(rows: List<String?>): String =
        rows.joinToString("\n") { it ?: DOC_UNREADABLE_ROW }

    // ══════════════════════════════════════════════════════════════════════════
    // P1-b：框里那一片**可以改**了 —— 改完按**行偏移**回写（ISSUE #228）
    // ══════════════════════════════════════════════════════════════════════════
    // P1-a 把框从"整个库"改成"一页的只读预览"，把"点开库要等几秒"这件事解决掉了。
    // 代价写在那一版的说明里：**框里改不了全文了**，编辑只能走「追加」一条与
    // 每条「删」。而"改错一个字"（改个错别字、补个标点、修一句被切坏的话）
    // 恰恰是编辑里最常见的动作 —— 它此前只能靠"删掉重加"，而重加会换掉向量、
    // 也换掉行号。
    //
    // P1-b 补上这一件事，而且**只补这一件**：框里那一片可以编辑，保存时按
    // **行偏移**把改动写回磁盘——没改的行，真值来自**磁盘**，不是框。
    //
    // ⚠ 这一句是 P1-b 与 P1-a 之前那一版的**根本差别**：
    //   旧版 `doSaveTexts` 拿"框里的全部内容"整份覆盖 `texts.jsonl`（框 = 全库，
    //   所以那是对的）；P1-b 之后框里只有**一页**，拿它整份覆盖 = 把整个库
    //   砍成一页。所以取真值的方向必须反过来：**框只提供"改了什么"，
    //   其余每个字节仍来自磁盘**。判据也钉在这一对上（见 `run_rag_doc_preview_guard.sh`）。
    //
    // ⚠⚠ 为什么**必须**是"行数不变"（改内容 = 换字，不是增删行）
    //   增行 = 在文件中间插入，本仓库的写盘面明确不支持（`appendEntries` 的说明：
    //   中间插入要把它之后**每一行**往后挪，与重建没有区别）；
    //   删行有它自己的入口（每条「删」，它走 `removeEntry`，那条路已经处理了
    //   "其后每行前移一位"）。两者混进"编辑框保存"里，会让一次保存同时是
    //   "改几个字"与"挪动几十行向量"，而后者一旦错位**不报错**（分数对、内容错）。
    //   所以：行数变了 -> 拒绝，并把两条真的走得通的路指出来（「追加」/「删」）。
    //   行数不变时，回写是**逐行对齐**的 1:1 替换 —— 没有任何行号需要重排，
    //   这也正是"按行偏移回写"这五个字的全部含义。

    /**
     * 编辑后的框内容按行拆开 —— 与 [docPreviewText] 的拼法**逐字互逆**。
     *
     * ⚠ 不 `trim`、不过滤空行：框里"少了一个空行"与"少了一行"在拼回去时是两件事，
     *   而 P1-b 靠"行数相等"来判定"这是一次改字，不是增删行" —— 在这里把空行
     *   吃掉，就等于把"用户删了一个空行"判成"行数没变"，于是那一次改动**静默丢失**。
     *
     * ⚠ `split('\n')` 会让末尾换行多出一个 `""`：框里多敲一个回车（行数 +1）
     *   必须被**看见**（它是一次增行 -> 拒绝），所以这里不丢掉那个空串。
     */
    fun docEditLines(text: String): List<String> = text.split('\n')

    /** 一行**读不出来**的占位（[docPreviewText] 写进框里的那一句）。 */
    const val DOC_UNREADABLE_ROW = "（这一行读不出来）"

    /**
     * 「框里这一片」→ 「要写回磁盘的那几行」（`null` = **拒绝**这次编辑）。
     *
     * ══════════════════════════════════════════════════════════════════════════
     * 返回值为什么是"相对偏移 + 只含改过的行"
     * ══════════════════════════════════════════════════════════════════════════
     * 调用方拿它去 [RagIndexStore.replaceRowsInPlace]：`firstIndex` 是这一片在
     * **正文文件里的行号**，`texts` 与它逐行对齐。**没改的行不进 [DocEditPlan]** ——
     * 磁盘上那些行原封不动（这是"按行偏移回写"能比"整份覆盖"安全的原因：
     * 框里读到的、与磁盘上真实的，即使因为某种原因不一致，也**只影响改过的那几行**）。
     *
     * ══════════════════════════════════════════════════════════════════════════
     * 拒绝的三件事（全都返回 `null`，调用方负责把原因说给用户）
     * ══════════════════════════════════════════════════════════════════════════
     *   ① **行数变了**（增行 / 删行）。见类头那段：本仓库的写盘面不支持中间增删，
     *      两者各有入口（「追加」/「删」）。**允许**它会让一次保存变成"改字 + 重排
     *      行号"，而重排错了不报错。
     *   ② **改到了一行"读不出来"的**（[DOC_UNREADABLE_ROW] 那一行）。那一行在磁盘上
     *      是坏的（非法 JSON / 截断），框里显示的是一个**占位串**。把用户看到的
     *      占位串当成新内容写下去 = 拿一句我们编的话覆盖掉磁盘上那一段原字节 ——
     *      内容换了、而且换成了不是他写的东西。所以：那一行**只许原样不动**，
     *      动了就拒绝（要修它请点「建库/重建」）。
     *   ③ **一行都没改**（`texts` 为空）。这是一次"打开看了看" —— 不该产生写盘，
     *      也不该把索引判成"需重建"（本仓库对"看了再存"的判据：保存是幂等的）。
     *
     * ⚠ 只**改字**（内容变了、行数与位置都没变）才是本版支持的编辑 —— 上面的
     *   ①③ 两条合起来正好是这个范围。
     *
     * @param rows  这一片在框里**画出来时**用的行（来自 `readEntriesAligned`，
     *              下标即行号；`null` = 那一行读不出来）
     * @param first 这一片第一行在**正文文件里的行号**（= [docPreviewRange] 的起点）
     * @param edited 用户改完之后框里的内容
     */
    fun docEditPlan(rows: List<String?>, first: Int, edited: String): DocEditPlan? {
        if (rows.isEmpty() || first < 0) return null
        // 行数必须相等 —— 见上面 ①。`docEditLines` 与 [docPreviewText] 互逆，
        // 所以"没动过"的框在这里必然得到与 `rows.size` 相等的行数。
        val lines = docEditLines(edited)
        if (lines.size != rows.size) return null
        val out = ArrayList<String>(rows.size)
        val idx = ArrayList<Int>(rows.size)
        for (i in rows.indices) {
            val old = rows[i]
            val now = lines[i]
            // 这一行本来就读不出来：只许原样（占位串原封不动）—— 见上面 ②。
            if (old == null) {
                if (now != DOC_UNREADABLE_ROW) return null
                continue
            }
            // 没改的行**不进计划**：它们的真值来自磁盘，框里这份只是渲染。
            if (now == old) continue
            // 空行：一个条目不许被改成空的（`removeEntry` 也以 `isEmpty()` 拒空行，
            // 而正文里的空行会让"行号 = 下标"这条口径直接失效）。要删掉它请用「删」。
            if (now.isEmpty()) return null
            idx.add(first + i)
            out.add(now)
        }
        if (out.isEmpty()) return null      // ③ 一行都没改：这不是一次编辑
        return DocEditPlan(idx, out, rows.size)
    }

    /**
     * 一次**按行偏移**的正文编辑计划（见 [docEditPlan]）。
     *
     * [indices] 与 [texts] 逐位对齐：`indices[k]` 是正文文件里的行号，
     * `texts[k]` 是那一行改完之后的内容。**没改的行不在这里**。
     *
     * [sliceRows] 是这一片一共几行 —— 它不参与写盘，但**必须**一路传到确认框那里：
     * 用户按下的那一刻要说清"这一片有 N 行、其中 M 行被改"，而这两个数在屏幕上
     * 都没有别的地方能看出来（框里只有渲染出来的文本）。
     */
    data class DocEditPlan(val indices: List<Int>, val texts: List<String>, val sliceRows: Int) {
        val changed: Int get() = indices.size
    }

    /**
     * 可编辑预览态下、正文框**上面**那一行说明（`null` = 不必说）。
     *
     * 它取代的是 P1-a 那一版[docEditableNote] 之前的那句"只读预览"（只读预览）—— 与它的差别只有一处，
     * 但那一处是全部：**这个框能改**。所以要说清的四件事里，
     * 最后一件从"要改去哪儿改"变成"改完怎么存"：
     *   ① 这是**这一页**（不是全部）；② **能改**（不是只读预览）；
     *   ③ 改的是**条目正文**（一行一条，空行会被拒）；④ **改完要按「保存本页改动」**，
     *   且保存只写这一页——**其余页一个字节都不动**。
     *
     * ⚠ ④ 必须说：这一版的"保存"与旧版的"保存正文"**不是同一件事**（旧版整份覆盖，
     *   这一版只回写改动的那几行）。两句话长得像而后果相反 —— 用户按旧的理解去用，
     *   会以为"我这一改整个库都存了"，而其实**只有这一页**。这正是必须出声的地方。
     *
     * @param total 库里一共多少条
     * @param page  当前第几页
     */
    fun docEditableNote(total: Int, page: Int): String? {
        if (total <= 0) return null
        val pages = rowPageCount(total)
        val p = page.coerceIn(1, pages)
        val r = rowPageRange(total, p)
        val head = if (pages <= 1) "▸ 可编辑：这一页的 $total 条（全部）"
                   else "▸ 可编辑：第 ${r.first + 1}–${r.last + 1} 条 · 第 $p/$pages 页"
        // ⚠ 最后一句（"只重算改过那几条的向量、无需重建"）是 ISSUE #228 新特性的
        //   出声处。用户在**改之前**就该看到它 —— 因为旧口径（改字 = 整库重建）
        //   是一个很强的心理门槛，而它正是这一版要消掉的负担。
        return "$head，一行一条，改完点「保存本页改动」。" +
            "保存**只写这一页**（其余 $pages 页里的内容一个字节都不动），" +
            "并只**重算改过那几条的向量**（无需重建，检索照常）；" +
            "要增删条数请用下面每条的「删」或「追加」"
    }

    /**
     * 一次保存之后给用户的那句话（`null` = 没有改动，不该有这句话）。
     *
     * ⚠ 必须点出"只写了 M 行 / 这一片的 N 行"与"其余页没动"：保存这件事的后果
     *   在屏幕上**看不出来**（框里还是那一页、列表还是那些条），而它的真相
     *   （改了几行、写进了哪个库的第几行）只有这一句话能说。少这一句，
     *   "我改的那处到底存了没有"就只能靠用户自己去别处翻 —— 而翻不到时就重导，
     *   重导会让条目翻倍。
     *
     * @param name  库名（说清写进了哪里）
     * @param plan  这一次回写的计划
     */
    fun docEditSavedNote(name: String, plan: DocEditPlan): String? {
        if (plan.changed <= 0) return null
        return "已把 ${plan.changed} 行改动写回「$name」" +
            "（这一片共 ${plan.sliceRows} 行，其余行与其余页未改动）；" +
            "改过的条目**需要「建索引/重建索引」**之后才按新内容检索"
    }

    /**
     * 一次「改字 + **重算向量**」保存之后给用户的那句话（ISSUE #228 的新特性）。
     *
     * 与 [docEditSavedNote] 是**两句不同的话**，而它们的差别正是本轮新增的能力：
     *   · 那一句说「需要重建之后才按新内容检索」（改过的行只有新**正文**、
     *     向量还是旧的）；
     *   · 这一句说「**无需重建**，检索照常」（改过的那几行连同向量一起换掉了）。
     *
     * ⚠⚠ 这一句**必须**把"只重算了这几条、其余向量原位保留"说出来。
     *   保存的后果在屏幕上**看不出来**（框里还是那一页），而用户对"改字 = 要重建"
     *   这件事有**旧的习惯性预期**（P1-b 与更早的版本都是那样）。不说清，
     *   他会去找"重建"按钮、或者干脆不敢改 —— 而这两件都是这一版要消掉的负担。
     *
     * @param name 库名（说清写进了哪里）
     * @param plan 这一次回写的计划
     */
    fun docEditVectorNote(name: String, plan: DocEditPlan): String? {
        if (plan.changed <= 0) return null
        return "已把 ${plan.changed} 行改动写回「$name」并**重算了这几条的向量**" +
            "（这一片共 ${plan.sliceRows} 行，其余行与其余页未改动）；" +
            "**无需重建**，检索照常可用，命中的就是新内容"
    }
}
