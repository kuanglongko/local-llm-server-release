package com.xiaowan.localinference

/**
 * 远端知识库（RAG 阶段 3）的**协议层可见面**。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么"远端注入"必须有一个协议层字段（而不是只在正文里放 `[知识库]`）
 * ══════════════════════════════════════════════════════════════════════════
 * 远端路径与前两阶段有一个本质差别：**服务端从无状态变成有状态了**。
 *
 * 在 App 内，"要不要注入"这件事的因果闭环是完整的 —— 开关就在同一屏，
 * 注入的位置（最后一条 user 之前）也是我们自己控制的历史。而远端是：
 *
 *     调用方发 messages -> （服务端按一个它看不见的开关）可能改写了这轮 prompt -> 回答
 *
 * 调用方对那个开关**一无所知**。于是"回答里混进了知识库内容"与"模型自己
 * 产生了幻觉"，在调用方看来**完全同形**：接口 200、结构合法、只是内容可疑。
 * 而这两种情形的处置方向是相反的（前者是配置问题、要去关开关；后者是模型问题、
 * 要改采样/换模型）—— 判成错的那个会让人朝反方向查很久。
 *
 * 项目里已经有一条**形状完全相同**的现成机制可以照着做：思考开关的软注入
 * （[ThinkingControl]），它就是"服务端偷偷改了 prompt 而客户端不知情"的解法。
 * 这里沿用同一套三层提示：
 *
 *   | 层         | 载体                              | 为什么不能省 |
 *   |------------|-----------------------------------|--------------|
 *   | 可判别锚点 | 注入块行首的 `[知识库]`（已有）    | 回答正文里人眼唯一能分辨的东西 |
 *   | 协议层可见 | `/health` 的 `rag_*` 字段 + 本轮响应里的 `local_rag` | 客户端**发请求前**就能读，不必等回答出来才发现 |
 *   | 明说原因   | 日志（每次注入/每次跳过都有一行） | "被注入"与"模型答偏了"必须能分开 |
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么这个字段**只加在"确实注入了"的响应上**（而不是恒定出现）
 * ══════════════════════════════════════════════════════════════════════════
 * 与 `logprobs` / `logit_bias` 那批协议字段同一条准则：**字段不存在时必须与
 * 引入本特性之前逐字节同行为**。没注入的响应里多一个 `"local_rag":null`
 * 会让"没开"与"开了但没命中"这两种情形在协议上完全没有区别 —— 而那正是
 * 我们要消除的那种"同形"。所以：
 *
 *   · 没注入 —— 响应里**一个字节都不多**（老客户端逐字节同旧行为）；
 *   · 注入了 —— 响应里多一个 `local_rag` 对象，**含库名与条数**。
 *
 * ⚠ 这个字段**不是** OpenAI 官方字段。多出来的字段按 OpenAI 客户端的一般做法
 * 是**忽略**（它们按字段名取值，不校验未知字段），所以加它不破坏兼容性 ——
 * 这一点与 `finish_reason: "cancelled"` 是同一个取舍，那里已经先例过。
 */
object RagProtocol {

    /**
     * 一次**实际发生**的注入：库名 + 注入条数。
     *
     * 为什么要带"条数"而不只是一个布尔：`rag_injected=true` 仍会让"注入了 1 条"
     * 与"注入了 20 条（把整个 ctx 挤满）"同形 —— 而后者是"回答突然变差"的
     * 一个真实成因（知识库内容把本轮提问挤掉了）。条数是那个可归因的量。
     */
    data class Injection(val kb: String, val count: Int)

    /**
     * 响应里的 `local_rag` 字段片段（**含前导逗号**）；没有注入时返回**空串**。
     *
     * 返回空串而不是 `,"local_rag":null`：见文件头最后一段 —— 一个恒出现的
     * 空值会让"没开"与"开了没命中"在协议上不可分，那正是要消除的同形。
     */
    fun responseField(inj: Injection?): String =
        if (inj == null) "" else ",\"local_rag\":{\"kb\":${inj.kb.toJsonStr()}," +
            "\"injected\":${inj.count}}"

    /**
     * `/health` 的库名字段值 —— 已是**可直接拼进 JSON 的字面量**（含首尾引号）。
     *
     * 为什么做成"返回一个已经带引号的串"而不是让 `healthJson()` 写
     * `"rag_remote_kb":${remoteKb.toJsonStr()}`：库名是用户输入，引号/反斜杠/换行
     * 都会破坏整份响应，而 `/health` 一旦非法 JSON，探针会把**健康的服务**判成不可达
     * （Issue #77 就是这个形态）。转义点收在**一处**，拼装处就只剩"插值"这一件事。
     *
     * ⚠ 必须**返回引号**而不是返回裸串：裸串拼出来是 `"rag_remote_kb":我的库`（非法 JSON），
     * 而那正是本函数要防的错法。
     */
    fun kbJson(kb: String): String = kb.toJsonStr()

    /** JSON 字符串转义：库名是用户输入，不能直接拼进 JSON（引号会破坏整份响应）。 */
    private fun String.toJsonStr(): String {
        val sb = StringBuilder(length + 16).append('"')
        for (c in this) when (c) {
            '"' -> sb.append("\\\"")
            '\\' -> sb.append("\\\\")
            '\n' -> sb.append("\\n")
            '\r' -> sb.append("\\r")
            '\t' -> sb.append("\\t")
            else -> if (c < ' ') sb.append("\\u%04x".format(c.code)) else sb.append(c)
        }
        return sb.append('"').toString()
    }
}
