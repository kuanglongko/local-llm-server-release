package com.xiaowan.localinference

/**
 * 角色卡（V1）：给会话的 `system` 起个**名字**。
 *
 * 纯逻辑，不碰 Context / 文件系统，可在宿主上单测（同 [SessionCleanup] / [SessionQuota]）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 这一版解决的是什么，不解决什么
 * ══════════════════════════════════════════════════════════════════════════
 * 先说清边界，否则"角色卡"三个字会被读成 SillyTavern 那套（描述/首条消息/
 * 备用问候/个性/场景/示例消息/世界书）。**V1 一个都不做**，只做三件事：
 *
 * ① **可复用的名字** —— 把一段 `system` 存进卡片库，下次点一下就能用，
 *    不必再从别处复制粘贴。这是"方便"，不是"新功能"（今天手打完全等效）。
 * ② **切卡时不静默** —— 换 `system` 会把 KV 前缀的公共长度打到 **0**
 *    （`system` 在 pos 0，前缀是逐 token 比出来的），整段历史全量重算。
 *    此前这是用户手动操作、一天个位数次；有了卡片就是"点一下"，
 *    频次上一个量级，而**现象没有任何提示**（用户只会觉得"切了个卡片手机就烫了"）。
 *    V1 的做法：切卡**显式**作废 KV 账本 + 通知一次，不留给用户猜。
 * ③ **删卡不裸奔** —— 会话存的是**内容快照**（[SessionStore] 的 `cardSnapshot`），
 *    不是一个 id。只存 id 的话，卡片一删，那个会话的人设**静默消失**，
 *    而它照旧能打开、照旧能聊，只是"回答怪怪的"（同形于模型抽风）。
 *
 * ⚠ **卡片等于那段 `system` 文本，不等于别的任何东西。** 所以它没有
 * "格式"、没有"分区"、没有占位符替换 —— 那些是 V2，而它们每一个都需要
 * 自己的一族判据（占位符替换尤其：注错了没有任何症状，只能在纯函数里做）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么卡片库**不进会话配额**，却必须写进文档
 * ══════════════════════════════════════════════════════════════════════════
 * `SessionQuota.MAX_TOTAL_CHARS` 数的是**会话正文**（`messages[].content`）。
 * 卡片库是另一份文件，天然不进那个数。这是**有意的**：配额防的是"喂给模型的
 * 历史体量"，而卡片只有被选中的那**一张**才会进 prompt（其余只是存在磁盘上）。
 *
 * 但"不进配额"不等于"不用记账"：卡片库确实占磁盘，而它此前不在
 * README 的「数据存放位置」表里 —— 一个新用户看不到它、一个空间告警也
 * 归因不到它。所以 [MAX_CARDS] / [MAX_CARD_CHARS] 在这里**单独**设两道线，
 * 处置也单独说（[CardFault]），与配额那一套不共用判据。
 */
object RoleCard {

    /**
     * 卡片库最多存几张。
     *
     * 数字是拍的，但它**有下界**：这个数的用途是防"一份几千张的卡片包被批量
     * 粘进来"，不是防正常使用。手机上一个用户认真写的卡片不会超过几十张。
     * 200 与 `SessionQuota.MAX_SESSIONS_WARN` 同量级 —— 两处用同一个直觉
     * （"到两百条就该整理了"），但**判据不同源**：那个只提示、这个真的拦。
     */
    const val MAX_CARDS = 200

    /**
     * 单张卡片 `system` 的字符上限。
     *
     * 与 `SessionStore.MAX_CHARS`（24000，喂给模型的历史总量）不同源，但取同一个
     * 量级：一张卡片超过 24k 就已经比整个会话预算还大了，那时候要改的是这段
     * 提示词，不是上限。
     */
    const val MAX_CARD_CHARS = 24000

    /**
     * 一张角色卡。
     *
     * `id` 只在**卡片库内部**有意义（改名不改 id、改文案不改 id）——
     * 会话侧存的是 `cardSnapshot` 而不是 id（见文件头 ③）。所以 id 可以随时
     * 重新生成而不影响任何已存在的会话，这一点是刻意的。
     */
    data class Card(
        val id: String,
        val name: String,
        val system: String,
        val createdAt: Long = 0L,
        val updatedAt: Long = 0L,
    )

    /**
     * 卡片库读盘时的**毛病**，与"读到的那一份"分开报。
     *
     * 为什么不塌成一个"读失败"：三种毛病的处置完全不同 —— 文件损坏要重建，
     * 超限要删卡片，坏行要告诉用户"有 N 张没读出来"。一句"卡片库读取失败"
     * 会让用户既不知道丢没丢东西，也不知道该做什么。
     */
    enum class CardFault {
        /** 没有卡片库文件。**绝大多数用户**的常态，不是错误，不许出声。 */
        NONE,

        /** 文件在、但读不出来（损坏 / 不是合法 JSON）。处置：当作空库 + 出声。 */
        UNREADABLE,

        /** 顶到 [MAX_CARDS]，多出来的没读进来。处置：告诉用户实际收了几张。 */
        OVER_LIMIT,
    }

    /** 读盘结果：**一部分**卡片 + 一份毛病说明。两者都要有，不许只有一样。 */
    data class Loaded(
        val cards: List<Card>,
        val fault: CardFault = CardFault.NONE,
        /** 被丢弃的卡片条数（超限之外的：缺名字、缺 id、正文超长）。 */
        val dropped: Int = 0,
    )

    /**
     * 卡片**名字**的规范化：两端空白去掉，内部换行折成空格。
     *
     * 为什么折换行：名字会进下拉列表（单行控件），带换行的名字在那里会被
     * 压成一行而中间**看不出分隔**（"小万\n助手" 显示成"小万助手"）——
     * 用户看到的与存的不一样，而这是最容易归因错的那类不一致。
     */
    fun normalizeName(raw: String): String = raw.replace('\n', ' ').replace('\r', ' ').trim()

    /**
     * 卡片**正文**的规范化：只去掉两端空白。
     *
     * 刻意**不**折换行、不压缩空行：`system` 是喂给模型的文本，里面的换行
     * 与空行往往是有结构的（小标题、分段）—— 替用户重排等于静默改他的设定，
     * 而"改了设定，回答没变"与"模型抽风"同形。
     */
    fun normalizeSystem(raw: String): String = raw.trim()

    /**
     * 校验一张待存/待改的卡片，返回**不能用的原因**（能用则 null）。
     *
     * 为什么把"名字"也判进来（而不只是自动生成一个）：卡片下拉里显示的就是
     * 名字。一张没有名字的卡片在列表里是一行空白 —— 用户选它的时候**不知道
     * 自己在选什么**，而选错了的症状是"人设不对"，与"我记错了"同形。
     * 所以宁可在存的时候拦住他，也不要存下一张选不出来的卡。
     */
    fun validate(name: String, system: String): String? = when {
        name.isEmpty() -> "卡片名不能为空（下拉列表里要靠它认人）"
        system.isEmpty() -> "卡片内容不能为空（空的卡片与「不用卡片」没有区别）"
        name.length > MAX_NAME_CHARS -> "卡片名最长 $MAX_NAME_CHARS 个字符（当前 ${name.length}）"
        system.length > MAX_CARD_CHARS -> "卡片内容最长 $MAX_CARD_CHARS 个字符（当前 ${system.length}）"
        else -> null
    }

    /** 卡片名长度上限。它是**下拉列表**的一行，不是正文。 */
    const val MAX_NAME_CHARS = 40

    /**
     * 新建一张卡片（id 由这里生成，调用方不碰）。
     *
     * 与 `SessionStore.create` 同一种 id 形状（时间戳 36 进制 + 随机后缀）：
     * 跨设备不会有冲突，于是"导入一份卡片库"不必做 id 去重（本版也没有导入）。
     */
    fun newCard(name: String, system: String, now: Long): Card {
        val id = now.toString(36) + ((Math.random() * 1e4).toInt().toString(36))
        return Card(id, normalizeName(name), normalizeSystem(system), now, now)
    }

    /**
     * 卡片库是否还能再收一张。
     *
     * 与 `SessionQuota.decide` 的**同一格**口径：`used + incoming <= 上限`
     * 是闭区间（刚好放得下必须收），差一就拒会让用户对着"刚好放得下"的
     * 一张卡反复重试同一个操作。
     */
    fun canAdd(current: Int): Boolean = current < MAX_CARDS

    /**
     * 一张卡片在会话里**是不是仍然有效** —— 即"会话的人设快照与卡片库还对不对得上"。
     *
     * ══════════════════════════════════════════════════════════════════════════
     * 为什么这个判据必须存在（它就是"删卡不裸奔"那条的可见面）
     * ══════════════════════════════════════════════════════════════════════════
     * 会话存的是**快照**（`cardSnapshot`），所以卡片被删/被改名/被改文案之后，
     * 那个会话**照旧能聊天**，用的是快照里那段文本。这是 V1 的核心设计
     * （只存 id 的版本在这里会静默失去人设）。
     *
     * 但"能聊"不等于"用户知道自己在用一张已经不在库里的卡"。三态：
     *
     * - [Match.NONE]：这个会话没用卡片（前端显示"不用卡片"）；
     * - [Match.OK]：库里那一张与快照**逐字节相同**（正常状态）；
     * - [Match.STALE]：卡片不在了、或它的内容已经与快照不一样了。
     *   用户必须看得见这件事，否则他改了卡片却发现"会话没跟着变"
     *   （那是**对的** —— 快照不变，会话就不变），而现象只是"改了没生效"。
     *
     * ⚠ 判据是"**内容**逐字节相同"，不是"id 还在":
     *   只比 id 会把"卡片改了文案"判成 OK —— 那正是最容易让用户以为
     *   "改了卡片、所有用了它的会话都跟着变"的那种错法，而事实相反。
     */
    enum class Match { NONE, OK, STALE }

    fun match(cardId: String, cardSnapshot: String, cards: List<Card>): Match {
        if (cardSnapshot.isEmpty()) return Match.NONE
        val hit = cards.firstOrNull { it.id == cardId } ?: return Match.STALE
        // 两边都过 `normalizeSystem` 再比，**不假设**入参已经规范化过。
        //
        // 上一版只规范化左边（库里的那一份），于是"快照两端带空白、库里没有"
        // 被判成 STALE —— 那会让聊天页显示一句"卡片已修改"、并让用户点一次
        // **没有任何效果**的"用新内容覆盖"（覆盖完再比还是 STALE，因为覆盖
        // 写进去的是规范化后的文本，而比较又只规范化了一边）。恒假的提示
        // 比没有提示更坏：用户会学会无视这一行，而它要说的正是"你丢过什么"。
        return if (normalizeSystem(hit.system) == normalizeSystem(cardSnapshot)) Match.OK
        else Match.STALE
    }

    /**
     * 把"当前该用哪段 `system`"算出来。
     *
     * ══════════════════════════════════════════════════════════════════════════
     * 为什么**快照优先**，而不是"按 id 去库里现取"
     * ══════════════════════════════════════════════════════════════════════════
     * 「按 id 现取」看起来更"一致"（改了卡片所有会话一起变），但它有一个
     * 不可恢复的坏处：**卡片一删，那个会话的人设就没了**，而会话本身照旧
     * 打开、照旧能聊，只是回答不对 —— 用户要过几天才可能发现，且无从归因。
     *
     * 「快照优先」的代价是"改了卡片，已有会话不跟着变"。这个代价是**可见的**：
     * [Match.STALE] 会在聊天页那一行常驻显示，用户点一下就能"用新内容覆盖本会话"。
     * 两个方向都要付一点代价，那就选**代价可见**的那个。
     *
     * `snapshot` 为空 = 这个会话还没用过卡片 → 落回用户手打的 `system`
     * （即"不用卡片"这一档的语义，与 V1 之前的行为逐字相同）。
     */
    fun effectiveSystem(cardSnapshot: String, typedSystem: String): String =
        if (cardSnapshot.isNotEmpty()) cardSnapshot else typedSystem
}
