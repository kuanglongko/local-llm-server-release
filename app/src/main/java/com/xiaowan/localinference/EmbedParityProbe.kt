package com.xiaowan.localinference

/**
 * 「向量逐位比对」用的**固定样本集**（ISSUE #269 第 5 步）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么样本要**写死**，而不是"拿当前库里的几条"
 * ═══════════════════════════════════════════════════════════════════════
 * 这个对照的结论是**跨机器、跨版本**要对得上的一条断言（"批大小改了，
 * 向量还是不是同一些数"）。若样本来自"当前选中库"，两张截图（或两个版本）
 * 的结论会来自**不同文本** —— 那时"上次整批逐位相同、这次有几条不同"
 * 就分不清是环境变了还是文本变了。写死的样本让同一个结论可以在
 * ISSUE #269 里被跨版本比对。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么是这几条（每一条都在钉一个**会让向量变得不同**的边界）
 * ═══════════════════════════════════════════════════════════════════════
 * 合批与逐条两条路的差别在"同一批里每条的 token 数不同"这件事上最尖锐：
 *   · 长度差异大 -> 每条的位置预算与 padding 方式不同（`plan_batch` 要
 *     给每行分配 seq、算每条的 `pos`）；
 *   · 超长 -> 触发截断（两条路的截断点必须**同一个**，否则编的不是同一段）；
 *   · 多语言 / 代码 -> tokenize 出来的 token 数与字节数不成比例，
 *     而那正是"按字节算的预算"最容易岔开的地方。
 * 所以样本刻意取了"长短悬殊 + 含超长 + 含多语言"这一组（**4 条**，
 * 条数口径见对象头"为什么两组各 4 条"），而不是几条长度相近的普通句子 ——
 * 后者在两条路上很可能本来就相同，于是"验过了"其实什么都没验到。
 *
 * ⚠ `LONG` 那条**刻意超过单条 ctx 预算**（见 [LONG_REPEAT]）：它要走到
 *   截断那一支，而"两条路截断点不同"是本仓库记录过的一类静默失效。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么是**两组**（[TEXTS] 长短悬殊 + [SAME_LEN] 等长）
 * ═══════════════════════════════════════════════════════════════════════
 * [TEXTS] 那组刻意取"长短悬殊 + 超长"，于是它**同时**变了两件事：批布局，
 * 与"不等长导致的 padding / `split_equal`"。首轮真机报出「6 条里 1 条不同」，
 * 而那 1 条踩到的是哪一个，只有 [SAME_LEN] 能把它们分开 —— 它把"长度齐不齐"
 * 这一个变量拿掉了。详见 [SAME_LEN] 的说明。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么两组各 **4 条**（不是各 6 条）
 * ═══════════════════════════════════════════════════════════════════════
 * 条数与**批大小**（`LlmEngine.kEmbedBatchDefault` / native 的 `kEmbedBatchRows`，
 * 默认 8）对齐：两组各 4 条 = 一批只装一半（8 = 2×4），走两次 `embedBatch`。
 *
 * 为什么"对齐"重要：本对照的结论是**跨版本**要对的那一条（"0.9.218 那句待验
 * 断言到底成立没有"）。条数与批大小不对齐时（如 6 条 / 批 8，批里还剩两个空位），
 * 条数一变就去不了同样的图 —— 于是"上次这样、这次那样"多出"图不一样"这个变量，
 * 分不清是环境变了还是样本变了。这条由守卫正面钉住（判据读 `kEmbedBatchDefault`，
 * 样本数不整除它就红）。
 *
 * ⚠ 条数少了不等于覆盖弱了：每一条仍钉着它原来那个边界（见 [TEXTS] 里逐条注释），
 *   只是不再重复取"同类的第二条"。[TEXTS] 把原来的"长句"与"超长"两条**并成了
 *   一条**（长 + 多行 + 超长），省掉的是重复的变量，不是覆盖。
 */
object EmbedParityProbe {

    /**
     * 超长样本的重复次数。乘出来约 2000+ 字（≈ 1500~2500 token），
     * 在多数嵌入模型的 `n_ctx_seq`（常见 512~4096）之上会触发截断 ——
     * 这正是这一条样本的目的（见对象头）。
     */
    private const val LONG_REPEAT = 40

    /** 超长样本的一句话（重复 [LONG_REPEAT] 次）。 */
    private const val LONG_SENTENCE = "天道酬勤，向量嵌入的截断点必须在两条路径上是同一个，否则编的不是同一段文本。"

    /**
     * 固定样本集。**顺序不许改**（改了就等于换了实验条件，而结论仍被当成
     * 同一个 —— 见对象头"为什么样本要写死"）。
     */
    val TEXTS: List<String> = listOf(
        // ① 极短：单 token 级别的固定开销最突出。
        "你好",
        // ② 中等：夹在长短之间，最容易看出"位置预算"的差异。
        "向量检索是把文本编码成向量，再按余弦相似度找最接近的几条。",
        // ③ 多语言 / 符号：token 数与字节数不成比例。
        "hello world 123 —— テスト 🚀 test(len!=bytes)",
        // ④ 代码 + 超长：空白与缩进多（"按字节算预算"最容易岔开的一类），
        //    且带上 [LONG_REPEAT] 份长句 —— 这一条**同时**走到截断那一支，
        //    以及"多行 + 超长"的 padding（两条路的截断点必须同一个）。
        "fun main() {\n  val v = embed(\"x\")\n  println(v.size)\n}" +
            LONG_SENTENCE.repeat(LONG_REPEAT) + "}",
    )

    /**
     * 「**等长**」对照样本集（真机首轮读数逼出来的第二组，ISSUE #269 第 5 步）。
     *
     * ═══════════════════════════════════════════════════════════════════════
     * 为什么必须再有一组等长的（而不是只有上面那组长短悬殊的）
     * ═══════════════════════════════════════════════════════════════════════
     * [TEXTS] 那组刻意取的是"长短悬殊 + 超长"，于是它**同时**变了两件事：
     *
     *   · **批布局**（合批与逐条的图/调度不同）；
     *   · **不等长导致的 padding / `split_equal`**（native 侧会把每条补成等长，
     *     补出来的位置怎么参与 LAST 池化是本仓库真正没验过的那一格）。
     *
     * 首轮真机报出「6 条里 1 条不同」。而那 1 条到底踩到的是哪一个？
     * 只有**等长**的那一组能把这两个来源分开：
     *
     *   · 等长组**全绿** -> 差异来自**不等长的 padding/切分**，
     *     结论可以收窄成"等长合批是纯加速"（对长度相近的库能放行 g），
     *     而不是"合批整体不能用"；
     *   · 等长组**也有不同** -> 那是**批布局本身**在改语义，
     *     `g` 继续进指纹、这条路到此为止。
     *
     * ⚠ 两组样本必须**分开报、分开落读数**（不是并成一批）：并成一批时
     *   等长那几条的结论会被悬殊那几条淹掉，而"是哪几条不同"正是要问的东西。
     *
     * 长度上刻意取到"每条都一样"：这一组里唯一的变量只剩**批布局**，
     * 所以它一旦有差异，就必然是批布局造成的 —— 这就是它的全部价值。
     * 内容刻意各不相同（同一个句子重复若干遍时，两条路算出来的多半也相同，
     * 那样"验过了"其实什么都没验到 —— 与 [TEXTS] 对象头同一条理由）。
     *
     * ⚠ "每条都一样"指的是**字符数**（这一层不碰 tokenizer）：它不等于 token 数，
     *   但"字符数都一样"已经排除了"长短悬殊"这个来源 —— 而那正是它的用途。
     *   长度靠行尾的 `…` 补齐，改任何一条时**必须**同时补它（字符数全等由
     *   `EmbedParityTest` 正面钉住）。
     */
    val SAME_LEN: List<String> = listOf(
        "等长对照样本一：向量检索按余弦相似度排序，索引里的向量必须与查询向量同源，否则分数像随机。………………………………………………………………",
        "等长对照样本二：切块长度决定每条前向的 token 数，也决定 padding 要补出多少个位置来对齐；截断点还必须在两条路径上是同一个。",
        "等长对照样本三：合批把 n 条压成一次前向，省下来的是与 token 数无关的那一份固定开销。…………………………………………………………",
        "等长对照样本四：池化方式不同时同一条文本的向量也不同，所以指纹里必须把它一起带上。…………………………………………………………………………",
    )

    /**
     * 「**换批大小重建索引后，检索结果还是不是同一些行**」那组对照用的**查询集**
     * （与 [TEXTS] / [SAME_LEN] 是**同一批文本**，ISSUE #269 第 5 步）。
     *
     * ═══════════════════════════════════════════════════════════════════════
     * 为什么查询也要写死，而且必须**落在同一批文本里**
     * ═══════════════════════════════════════════════════════════════════════
     * 这一组量的不是"向量逐位相同吗"（那是 [TEXTS] 那组的事），而是
     * 「两套索引**搜出来的东西**还是不是同几条」。于是它有两个额外要求：
     *
     *   · **查询只能是同一批文本里的句子**（或它们的片段）—— 拿一句库外的
     *     文本来查，两侧都搜不到时会得到"命中集合全同（都空）"，而那**不是**
     *     结论（`EmbedRetrieveParity.Report.measured == false` 那一格）；
     *   · 必须**写死**（与 [TEXTS] 同一条理由）：结论是跨版本要对的那条，
     *     查询一换，"上次一样、这次不一样"就分不清是环境变了还是查询变了。
     *
     * ⚠ 三条查询刻意各不相同：[TEXTS] 的第 ①（极短）与第 ④（超长 / 多行 /
     *   代码）是两侧最容易岔开的两头，第 ②（中等）是中间档 —— 只查一条时
     *   "命中的是不是同几行"就可能落在一条本来就稳的查询上，而结论被当成
     *   整组的结论（与"样本要钉边界"同一条理由）。
     */
    val RETRIEVE_QUERIES: List<String> = listOf(
        TEXTS[0],
        TEXTS[1],
        TEXTS[3],
    )

    /**
     * 「检索对照」用的**正文语料**（不是查询）。
     *
     * ═══════════════════════════════════════════════════════════════════════
     * 为什么**不能**直接拿 [TEXTS] 当这一格的语料
     * ═══════════════════════════════════════════════════════════════════════
     * [TEXTS] 只有 **4 条**，而这一格取 `topK = 3`：任何查询的 Top-3 都是
     * "4 条里去掉 1 条"——**命中集合几乎恒等**（4 选 3 的集合只有 4 种，且
     * 两侧给同一组向量时，去掉的多半是同一条）。于是这一格在真机上永远报
     * "命中集合与名次都逐位相同"，而它**不是因为答案稳**，是因为样本太小 ——
     * 判据被样本的尺寸压住了，这格存在的唯一理由（判 `g` 能不能按库放行）
     * 因此得不到任何一行日志的支撑。
     *
     * 所以这一格的语料**单独一份**：**8 条**（与批大小默认值对齐），长短悬殊 ——
     * 既含 [TEXTS] 里那条会走到截断的超长文本（它是"批布局改变向量"的唯一来源），
     * 又垫了几条中等 / 短的把语料撑到 topK 的**两倍以上**，让"命中集合"真的有
     * 选择的余地（Top-3 从 8 条里挑，任何一条被挤出前 3 都能被看见）。
     *
     * ⚠ 顺序不许改（与 [TEXTS] 同一条理由：改了就是换了实验条件，
     *   而结论仍被当成同一个）；条数与批大小对齐（由 `EmbedParityTest` 正面钉住）。
     */
    val RETRIEVE_TEXTS: List<String> = listOf(
        TEXTS[0],
        TEXTS[1],
        TEXTS[2],
        TEXTS[3],
        "索引里正文行序与向量行序必须一一对应，错开一行就是「注入内容错位」那一族 bug。",
        "批大小是纯加速旋钮，前提是同一批里各条互不可见（按 seq 分块建注意力掩码）。",
        "top-k 取前几名由分数决定，而分数在两种批布局下允许有浮点级差异，所以判据落在集合上。",
        "编号五：四份公开语料各留一句锚文本，用来让检索对照的语料条数超过 topK 的两倍。",
    )

    /**
     * [RETRIEVE_TEXTS] 的查询集 —— **必须取自这份语料本身**（同 [RETRIEVE_QUERIES]
     * 那条理由：拿库外的句子来查，两侧都搜不到 -> "都空"会被读成"答案没变"）。
     *
     * 三条刻意取两头一中间：第 0（极短）、第 3（超长 / 多行 / 代码）、第 5（中等）。
     */
    val RETRIEVE_TEXTS_QUERIES: List<String> = listOf(
        RETRIEVE_TEXTS[0],
        RETRIEVE_TEXTS[3],
        RETRIEVE_TEXTS[5],
    )

    /** [SAME_LEN] 的正文行序号（检索对照里"命中的是不是同几行"要指得出是哪几条）。 */
    val SAME_LEN_QUERIES: List<String> = listOf(
        SAME_LEN[0],
        SAME_LEN[2],
    )
}
