package com.xiaowan.localinference

/**
 * JSON 字符串字面量的**唯一**转义实现（含首尾引号）。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么单独一个文件
 * ═══════════════════════════════════════════════════════════════════════
 * 这段循环此前在四个地方各写了一遍，逐字符相同：
 *   · [HttpApi]（`errJson` / `/health` / SSE 帧 / `/v1/models`）
 *   · [EmbeddingsApi]（错误响应 / `model` 字段）
 *   · [RagProtocol]（库名：用户输入，引号会破坏整份响应）
 *   · [ToolCalls]（工具名与 `arguments`）
 *
 * 它看起来短到"复制一份也无所谓"，但它坐在**协议正确性边界**上：漏掉
 * `\b`/`\f`、或将来要处理代理对时只改一处，另一条端点就会吐出坏 JSON，
 * 而症状是"某个客户端偶发解析失败" —— 没有异常、没有日志、HTTP 200。
 * `ToolCalls` 当初自带一份的理由是"HttpApi 里那份是 private，工具调用测试
 * 不编译整个 HTTP 层"，而本文件不依赖 Android，这个理由自然消失。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 与 [JsonSchemaFormat.escapeProbe] 的区别（刻意不合并）
 * ═══════════════════════════════════════════════════════════════════════
 * 那个函数的契约是"把一段原文压成**日志里的一行**"：不带首尾引号，
 * 转义集合与这里相同只是因为 JSON 的转义面恰好够用。两者用途不同
 * （一个拼响应体、一个给人看日志），合并会让其中一边的调用点多一次
 * 剥引号/加引号的动作，反而更容易写错。
 */

/**
 * 把 [this] 转成一个**完整的 JSON 字符串字面量**（含首尾 `"`）。
 *
 * ⚠ 返回值**自带引号**：手拼 JSON 时直接 `${s.jsonQuoted()}`，不要再包一层 ——
 *   多包一层会得到 `""...""`，而那是非法 JSON（org.json 会抛，浏览器按"响应
 *   格式错误"处理，两者都指向不了这里）。
 */
fun String.jsonQuoted(): String {
    val sb = StringBuilder(length + 16).append('"')
    for (c in this) when (c) {
        '"' -> sb.append("\\\"")
        '\\' -> sb.append("\\\\")
        '\n' -> sb.append("\\n")
        '\r' -> sb.append("\\r")
        '\t' -> sb.append("\\t")
        // 其余控制字符（< 0x20）走 \u00XX：JSON 不允许原样出现。
        else -> if (c < ' ') sb.append("\\u%04x".format(c.code)) else sb.append(c)
    }
    return sb.append('"').toString()
}
