package com.xiaowan.localinference

import android.content.Context

/**
 * 「上下文水位上限」这个**用户可调参数**的持久化与归一（ISSUE #426 方案 B+C）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么这是一个**上限**，而不是"装不下时才丢"的阈值
 * ══════════════════════════════════════════════════════════════════════════
 * 用户报的现象是：超长对话能生成之后，**之后每一条回答都跟前面没关系了**。
 * 机制在 [ContextBudget.plan]：丢历史是"丢到刚好装得下"，于是容量线附近
 * 每轮都要再丢一组 —— 每丢一次，KV 前缀起点就往后挪一次，模型看到的历史
 * 每轮都是新的一段，表现就是"忽然失忆、答非所问"。
 *
 * 解法不是"丢得更聪明"，而是**别在容量线上滑**：一越过水位就丢到水位的
 * 一半，然后在一个带里平稳跑（涨到水位再丢一半）。丢掉的那一轮只断一次
 * 复用，后面几十轮起点不动 —— 这比"每轮都在断"划算得多。
 *
 * 所以这一格是**水位**：`prompt + 生成 <= 每格容量 × 水位`。
 * 取 85% 作默认值：把最后 15% 留给"这一轮生成的回答比预期长"，
 * 而不是让回答去撞 `n_ctx` 的墙（撞墙那一轮的回答会被截断、且 `finish_reason`
 * 变成 length —— 用户读到的是"话说到一半就断了"）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么是**分档**而不是一个输入框
 * ══════════════════════════════════════════════════════════════════════════
 * 水位这个数没有"正确答案"，只有取舍：
 *   · 越高 -> 记得越多（少丢历史），但每次丢的时候断得越狠、撞墙的风险越大；
 *   · 越低 -> 跑得越稳（起点不爱动），但更早开始忘事。
 * 用户能判断的只有"我要多记住一点"还是"我要它别乱"，而这两件事在 5% 的
 * 精度上没有区别 —— 所以给五档（[LADDER]），并让每一档自带一句人话。
 *
 * ⚠ 不要做成滑杆或输入框：那会让人以为"调 1% 有意义"，然后花十分钟找一个
 *   体感上不存在的最优值。分档把选择成本压到一次点击。
 */
object ContextWatermark {

    /**
     * 键名。`%` 直接写进名字里 —— 这一格存的是**百分数**（85 而不是 0.85），
     * 而"存 85 还是 0.85"是这类设置最常见的分叉点（读错一次就是 8500%）。
     */
    const val KEY = "ctx_watermark_pct"

    /**
     * 默认水位（%）。用户原话："85% 作为默认上限"。
     *
     * 这个值也是 [LADDER] 里的一档 —— 两者必须是同一个数：默认值不在档位上时，
     * 设置页会显示"当前 85%，但没有任何一个按钮是亮的"，而用户没法把它调回去。
     */
    const val DEFAULT_PCT = 85

    /** 读写口；四条纪律见 [IntPref]（读、写两侧都走 [normalize]）。 */
    private val pref = IntPref(Prefs.RAG, KEY, DEFAULT_PCT) { normalize(it) }

    /**
     * 可选的档位（%）—— **转引** [ContextWatermarkPct.LADDER]，不在这里另写一份。
     *
     * 档位是判据的输入（[ContextBudget.plan] 按它算水位线），而判据必须能在宿主单测
     * 里跑；两份各写一遍时，界面会亮一个判据不认的档位 —— 而那种漂移在屏幕上
     * 与"生效了"逐字相同。
     */
    val LADDER get() = ContextWatermarkPct.LADDER

    /**
     * 读当前水位（**归一后**的百分数）。
     *
     * 归一拍在读这一侧（与 [EmbedCtxPref.get] 同一条理由）：磁盘上那份可能来自
     * 旧版本、或被人手改过 —— 而读到 0 会让水位变成 0（每轮都丢光历史），
     * 那是"功能坏了"而不是"设置了一个值"。
     */
    fun get(ctx: Context): Int = pref.get(ctx)

    /** 写当前水位（先归一，免得把一个跑不了的值落盘）。 */
    fun set(ctx: Context, value: Int) = pref.set(ctx, value)

    /** 这一格有没有被显式设过（`/health` 与设置页的"要不要显示默认"都要它）。 */
    fun isSet(ctx: Context): Boolean = pref.isSet(ctx)

    /**
     * 抹掉这一格（回到默认 85%）。**「还原默认设置」必须调它** ——
     * 与 [EmbedBatchPref.clear] 同一条理由：写一个默认值进去会让 [isSet] 仍为真。
     */
    fun clear(ctx: Context) = pref.clear(ctx)

    /**
     * 把任意输入钳到**这一格真能跑的区间**，并**吸附到最近的档位**。
     *
     * 吸附是刻意的：档位之外的数（比如 83）在手感和 85 上没有任何区别，而它会
     * 让设置页出现"五档都不亮、但当前值是 83"这种说不清的状态。归一成档位之后，
     * "当前值"永远能在屏幕上指出它对应哪个按钮。
     *
     * ⚠ 纯函数（不碰文件、不碰 Android），设置页与预算两条路共用 —— 两处各写一遍
     *   就会漂移，而漂移的症状是"设置页显示 90%、实际按 85% 裁"，一个字都没有。
     */
    fun normalize(value: Int): Int = ContextWatermarkPct.normalize(value)

    /**
     * 水位换算成**这一格能用到多少 token**（含生成）—— `ContextBudget.plan` 的唯一入口。
     *
     * @param ctx 每格容量（[ContextBudget.capacity] 的落值；<=0 = 未知 -> 返回 0）
     * @return 这一格的可用上限（token）；0 = 未知/不可用
     *
     * ⚠ 返回值**含生成**（它是"prompt + gen"的池子），不是"prompt 的上限"。
     *   两个数各起一个名字时，调用方一定会混用其中一个 —— 而混用的症状是
     *   "水位 85% 只用来限制 prompt，gen 又把剩下的吃掉"，也就是水位形同虚设。
     */
    fun limitTokens(pct: Int, ctx: Int): Int {
        if (ctx <= 0) return 0
        return (ctx.toLong() * normalize(pct) / 100L).toInt()
    }

    /** 一句话说明（设置页常驻行与日志共用，避免两处各写一份措辞）。 */
    fun describe(pct: Int): String {
        val p = normalize(pct)
        return when (p) {
            70 -> "70%：最早开始忘事，换来最稳的前缀复用（长会话几乎不再断）"
            80 -> "80%：偏向稳（比默认早丢一点，回答更长时不撞墙）"
            85 -> "85%（默认）：记得住 vs 跑得稳的折中"
            90 -> "90%：很记得住，但每次丢的时候断得更狠、生成长回答更容易撞墙"
            else -> "95%：最记得住（大 ctx 不浪费），但只给回答留 5% 的余量，" +
                "长回答撞墙、被截断的风险最大"
        }
    }
}
