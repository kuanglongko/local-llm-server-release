package com.xiaowan.localinference

/**
 * 会话库的**配额判据**（纯逻辑，不碰 Context / 文件系统，可在宿主上单测）。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么把上限从「会话个数」换成「总字符数」
 * ══════════════════════════════════════════════════════════════════════════
 * 上一版用 `MAX_SESSIONS = 50` 当硬闸门。但「会话个数」是个**代理指标**，
 * 它和真正在意的资源（磁盘占用、列表渲染条数）都不是线性关系：
 * 一个用户可能积累几百个"每天开一个新的"的短会话，每个都很小；
 * 也可能只有一个几万字的长会话。用个数去卡，卡住的是前者，放过的是后者 ——
 * 正好卡反了。
 *
 * 所以这里改成**两条线，职责分开**：
 *
 * - [MAX_TOTAL_CHARS] 是**硬闸门**：会话正文总字符数（≈ 磁盘占用）。
 *   超了**明确拒绝**并报出"已用 X / 上限 Y"，而不是静默截断或自动删最旧 ——
 *   那两种都是不可恢复的静默毁数据。2_000_000 字符 ≈ 6 MB（UTF-8 中文），
 *   放得下几百个普通会话，而对手机存储也不构成压力。
 * - [MAX_SESSIONS_WARN] 是**软提示**：只提醒，**不阻止**新建。真正的痛点是
 *   会话管理对话框一把塞全部条目（没有搜索、没有批量删），所以该限制的是
 *   「列表可用性」，不是「库里能放几个」。用个数值当"该清理了"的提醒线即可。
 *
 * 三条口径：
 *
 * ① **只卡新增，不卡已存在**。上限只在新会话写入（`create` / 导入 / 迁移）时判；
 *    读路径（`list` / `load`）永不因超限拒绝。旧数据已经超了也能正常打开 ——
 *    否则用户会陷入"打不开也删不掉"的死锁。
 *    ⚠ 这条口径同时意味着"**零增长的新增必须放行**"：建一个空会话不增加任何
 *    字符，它是用户整理旧会话的**唯一落脚点**。顶到上限后连一个空会话都建不出来，
 *    就是"打不开也删不掉"的另一种写法（详见 [decide] 的说明）。
 * ② **整份拒绝，不部分写入**。超限时不写半截就停，让调用方拿到明确结论再提示。
 * ③ **判据可复算**：`usedChars` 由调用方从真实数据算出（见 `SessionStore.usedChars`），
 *    不在这里自己读文件 —— 这里只做算术，好让边界能被穷举。
 */
object SessionQuota {

    /**
     * 正文总字符数的**硬上限**（≈6MB）。超了这个数就不再收新会话。
     *
     * 数字是拍的：它要大到"正常用户一辈子用不到"，小到"真撑满时手机还有余量"。
     * 一个 24k 字符的历史装满的会话是 24k，这个上限约等于 83 个这样的满会话，
     * 或几百个普通会话。
     */
    const val MAX_TOTAL_CHARS = 2_000_000

    /**
     * 会话个数的**软提示线**。**不阻止**任何操作，只在会话管理里提示"该清理了"。
     *
     * 从上一版的硬闸门 `50` 放宽到 200 的依据：50 是第一次做多会话时拍的数，
     * 不是从任何约束反推的；而列表真正难用的拐点在两百条上下（对话框没有搜索）。
     */
    const val MAX_SESSIONS_WARN = 200

    /**
     * 一次新增的**准入判决**。
     *
     * `usedChars` 是**判的时候**的占用（已含本机现有全部会话正文）；
     * `incomingChars` 是**这一批**要新增的正文量。`allowed == false` 时
     * `remaining` 仍是真实剩余量（可能为 0），供调用方拼"还能收 N 个字符"这类提示。
     */
    data class Decision(val allowed: Boolean, val usedChars: Long, val incomingChars: Long) {
        /** 距硬上限还剩多少字符（超限时为 0，不为负）。 */
        val remaining: Long get() = (MAX_TOTAL_CHARS - usedChars).coerceAtLeast(0L)

        /** 本次被拒时超出的字符数（未拒时为 0）。 */
        val over: Long get() = if (allowed) 0L else (usedChars + incomingChars - MAX_TOTAL_CHARS).coerceAtLeast(0L)
    }

    /**
     * 判一次新增能不能收。
     *
     * 判据只有一条：`已用 + 本次 <= 上限`（闭区间 —— 恰好放得下必须收）。
     * 刻意**不用** `MAX_SESSIONS_WARN` 参与判决 —— 它只是提示线，一旦让它拒绝
     * 新增，就退化回了"用个数硬卡"的老问题。
     *
     * ══════════════════════════════════════════════════════════════════════
     * 为什么"本次为 0"必须放行（哪怕已用已顶到上限）
     * ══════════════════════════════════════════════════════════════════════
     * 上一版的 `usedChars + incomingChars <= MAX_TOTAL_CHARS` 在
     * `used == 上限 && incoming == 0` 时判**拒绝**，而这一格恰好是
     * `create` 与 `createNoMigrate` 唯一会问的那一格（新会话的正文是 0）——
     * 后果是用户**顶到上限之后再也建不出一个空会话来整理**：
     *
     *   · 删旧会话？可以，但删除只腾出空间、不提供落脚点；
     *   · 想新建一个空会话把要留的内容搬过去？建不出来。
     *
     * 而 [SessionQuota] 的类注释里写着的第一条口径是
     * "**只卡新增，不卡已存在** …… 否则用户会陷入『打不开也删不掉』的死锁"。
     * 旧实现与它自己的口径正好相反：`incoming == 0` 不增加任何一个字符，
     * 它不是"新增"，它是**整理动作的入口**，所以它必须走 [零增长] 那一支。
     *
     * ⚠ 判据是 `incomingChars <= 0`（而不是 `== 0`）：负数没有意义，但它一旦
     *   出现（调用方算错），应当与 0 同处置（放行、且不把额度算小），
     *   而不是被当成"很小的新增"混进下面那个加法里。
     */
    fun decide(usedChars: Long, incomingChars: Long): Decision =
        Decision(
            allowed = incomingChars <= 0L || usedChars + incomingChars <= MAX_TOTAL_CHARS,
            usedChars = usedChars,
            incomingChars = incomingChars,
        )

    /**
     * 在**一批**待导入会话里，按预算**从前往后**收，返回能收下的条数。
     *
     * 与 [decide] 的分工：`decide` 判"这一个能不能进"，这里判"这一串能进几个"。
     * 导入是批量的，若整批一起判就会因为尾部一条超限而**把前面能收的也全丢**，
     * 那是更坏的失败方向（用户看到"什么都没进来"）。
     *
     * **停在第一条收不下的会话上，不跳过它继续试后面的**：跳过会让"收了 3 个、
     * 第 4 个太大、又收了第 5 个"，用户对着文件数不清到底进没进 —— 而且第 5 个
     * 能进只是因为第 4 个恰好很大，换个文件顺序结果就变。顺序一致才可解释。
     */
    fun acceptCount(usedChars: Long, incoming: List<Long>): Int {
        var used = usedChars
        var n = 0
        for (size in incoming) {
            if (used + size > MAX_TOTAL_CHARS) break
            used += size
            n++
        }
        return n
    }

    /** 会话数是否已到软提示线（只用来决定"要不要提示清理"，不拦任何操作）。 */
    fun shouldWarnCount(sessionCount: Int): Boolean = sessionCount >= MAX_SESSIONS_WARN
}
