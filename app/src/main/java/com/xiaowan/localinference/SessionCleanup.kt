package com.xiaowan.localinference

/**
 * 会话列表的**取数口径**（S4：搜索 + 按时间批量清理）。
 *
 * 纯逻辑，不碰 Context / 文件系统，可在宿主上单测。
 *
 * ══════════════════════════════════════════════════════════════════════════
 * 为什么这些判据要单独抽出来
 * ══════════════════════════════════════════════════════════════════════════
 * S3 把会话上限从「个数」换成了「正文总字符」，`MAX_SESSIONS_WARN = 200`
 * 只提示不拦人。放开之后用户面对的是**两三百条**会话，而会话管理对话框
 * 只有一个 `AlertDialog.setItems`：没有搜索、没有批量删 —— **上限放开了，
 * 用户却没有出路**。S4 就是补这条出路，而它有两类零症状的坏法：
 *
 * ① **搜索把筛出来的行当成了"全部"**。搜索框只该影响**屏幕上显示哪几行**；
 *    一旦它渗进删除/导出/清理的取数，用户会在搜索状态下删掉"看起来只有
 *    三条"的会话。而症状是"我的其它会话也不见了"，与"我手动删的"同形，
 *    无法归因。所以：**筛选是渲染层的取数，删除是库层的取数**，两者在
 *    类型上就分开（[visible] 只吃 [SessionStore.Info] 列表、返回列表）。
 *
 * ② **"清理"默认替用户勾好了要删的东西**。批量删是不可恢复的，而
 *    「按多少天没用过」这个阈值与用户心里的那个日子**从来不会刚好对齐**。
 *    默认全不勾 + 必须显式勾选才允许删除，是唯一不会误删的形态。
 *
 * 判据还都从"时间"这一个输入来（`now` 由调用方传入），不在内部读
 * `System.currentTimeMillis()`：这样"多少天算旧"这个边界能在宿主上被穷举，
 * 而"跑到第二天结果突然变了"这类漂移也就无从发生。
 */
object SessionCleanup {

    /**
     * 「清理」里可选的**天数档位**（最近使用超过 N 天的会话会被列出来）。
     *
     * 为什么是固定档位而不是让用户填数字：批量删不可恢复，而"填数字"这个
     * 交互在手机上要起键盘、要校验、还容易被当成"搜索框"。三个档位覆盖了
     * 全部真实需求（一周没碰 / 一个月没碰 / 一个季度没碰），且**每一个都是
     * 一个有名字的可见选项** —— 用户不必先想清楚"该填几"再动手。
     */
    val DAY_CHOICES = intArrayOf(7, 30, 90)

    /** 一档天数的默认取法（第 2 档 = 30 天）：给二级对话框一个不必猜的初值。 */
    const val DEFAULT_DAY_CHOICE = 30

    /**
     * 搜索：按**标题**做子串匹配，忽略大小写。
     *
     * 空关键字 = **不筛**（返回原列表），这与日志页那条「一个标签都不选 =
     * 全部」是同一口径：界面上不该出现"全部"这个额外档位。
     *
     * 为什么只搜标题：正文匹配要把每条会话的全文读进内存，而列表页是在
     * 打开对话框的那一帧上取数的 —— 几百条会话的文件读会在主线程留下
     * 一段明显的卡顿，而这一页目前根本没有正文搜索的交互位置。
     */
    fun filter(infos: List<SessionStore.Info>, keyword: String): List<SessionStore.Info> {
        val k = keyword.trim()
        if (k.isEmpty()) return infos
        return infos.filter { it.title.contains(k, ignoreCase = true) }
    }

    /**
     * 列出「超过 [days] 天没用过」的会话（`updatedAt` 早于 `now - days` 天）。
     *
     * **边界取闭区间**：`updatedAt == now - days` 的那一条**算旧**。
     * 与 [SessionStore] 的配额判据同一取法（`<=`），因为"刚好第 7 天"时
     * 用户的意图是明确的（他选的就是"7 天"这一档），把它排除会让同一批
     * 会话在连续两次打开时表现不一致。
     *
     * `updatedAt <= 0`（读不出来 / 老文件没写这个字段）**算旧**：这种会话
     * 在列表里本来就排在最后，且它没有任何可用的时间信息 —— 留着它会让
     * "清理 90 天"永远清不掉这类文件，而用户看不到原因。
     */
    fun olderThan(infos: List<SessionStore.Info>, now: Long, days: Int): List<SessionStore.Info> {
        val cutoff = now - days.toLong() * DAY_MS
        return infos.filter { it.updatedAt <= cutoff }
    }

    /** 一天有多少毫秒。抽成常量是为了让"天数 → 毫秒"这条换算只有一个写点。 */
    const val DAY_MS = 24L * 60 * 60 * 1000

    /**
     * 批量删除**之前**的三道闸，全在返回 `true` 才允许动手。
     *
     * - [ids] 是**用户显式勾选**的那几条（不是"列出来的那几条"）；
     * - `ids` 与当前库比对后取**交集**：勾选之后到点「删除」之间可能有别的
     *   路径改过库（比如另一处删除），按幸存者动手，不按当初勾的那份清单；
     * - **不得包含当前会话**的判据不在这里 —— 删当前会话是合法的（[SessionStore.delete]
     *   会切到最近一个），但它属于"删完之后界面怎么收场"，由调用方处理。
     *
     * 空集合一律拒绝：不做"一个都没勾就顺手清掉列出来的那些"。
     */
    fun canDelete(selected: Set<String>, existing: Set<String>): Boolean =
        selected.isNotEmpty() && selected.any { existing.contains(it) }

    /**
     * 取勾选清单与库的**交集**（顺序按 [infos] 的列表序，与 `list()` 的倒序一致）。
     *
     * 为什么要有这一步而不是直接删 `selected`：勾选之后库可能被别的路径改过
     * （删除、导入、清空）。按交集删，用户拿到的是"这些真的删掉了"；
     * 直接删 selected 里那些已经不存在的 id 会静默无事发生 ——
     * 而"点了删除，数量对不上"是最难解释的那种反馈。
     */
    fun resolve(infos: List<SessionStore.Info>, selected: Set<String>): List<SessionStore.Info> =
        infos.filter { selected.contains(it.id) }
}
