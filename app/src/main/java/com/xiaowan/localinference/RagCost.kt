package com.xiaowan.localinference

/**
 * 「建库要花多久」的**纯逻辑**估算 —— 只做算术，不碰 Android、不碰文件。
 *
 * ═══════════════════════════════════════════════════════════════════════
 * 为什么单独抽出来
 * ═══════════════════════════════════════════════════════════════════════
 * 建库的耗时**由条数主导**（逐条编码，一条一次前向），而且它与用户在界面上
 * 唯一能看到的东西（"我粘了几条"）**不成比例地增长**：
 *
 *   · 100 条 ≈ 5~30 秒（README 里那句承诺）；1000 条就是分钟级；
 *     16384 条（`maxChunks` 那个上限）在低端机上可能是几十分钟。
 *   · 而界面上此前唯一的提示是**开始之后**那一行"建索引中…（N 条）" ——
 *     用户是**按下去之后**才知道贵的，那时他已经在等（且不敢动，
 *     因为不知道还要多久、也不知道中断会不会弄坏什么）。
 *
 * 所以这里做两件事，都要求"简短"（用户拍板：**简短**提示，不是弹一篇说明书）：
 *   1. [buildPrompt]：条数够大时，**按之前**先问一句，把那句成本说清楚；
 *      条数小的时候返回 `null` —— 不打扰（大多数库就是十几条）。
 *   2. [estimateSeconds]：给一个**量级**（"约 10 秒" / "约 2 分钟"），
 *      不是精确值。报精确值是在装（真机差异极大），量级才是用户要的。
 *
 * ⚠ 这一层**只给读数、不做决定**：是否真的建、要不要拆小，由用户点。
 * 所以它返回字符串 / 数值，不返回值去驱动 UI 分支以外的逻辑。
 */
object RagCost {

    /**
     * 单条文本编码耗时的**保守**下界与上界（秒）。
     *
     * ═══════════════════════════════════════════════════════════════════════
     * 这一组数改过一次 —— 旧值把上界报小了 2.6 倍
     * ═══════════════════════════════════════════════════════════════════════
     * 旧值 0.05~0.30 秒/条来自 README 那句"100 条约 5~30 秒"。而 ISSUE #269
     * 的真机读数**比上界还差**：8e（骁龙 8 Elite）、每条约 400 字、
     * **1 秒 1.3 条**（≈0.77 秒/条）—— 旧口径（上界 0.30 秒/条）把 7000 条
     * 算成 2100 秒 ≈ 35 分钟，落进最后那档被显示成 **"可能十几分钟甚至更久"**，
     * 而真机要**两小时**。**提示报小了**比不提示更坏：用户按那句"十几分钟"
     * 决定现在开始，然后等了两小时，期间他一直以为自己遇上了卡死。
     *
     * 新值的取法把两件事分开：
     *   · 上界 `1.0`：真机实测的 0.77 再留一点余量。它代表"没调线程、
     *     或者机器/模型偏差"的那一档 —— 报提示时**必须**按这一档说，
     *     否则用户会按乐观值去规划。
     *   · 下界 `0.10`：本 issue 顺带把嵌入线程数默认值从写死的 4 改成
     *     按本机核数（见 `LlmEngine.defaultThreads`）之后，8 核机器上的
     *     预期改善档（不是承诺，是"调对了大概到这里"）。
     *
     * 为什么仍然是区间而不是一个数：真机差异（CPU / 模型大小 / 文本长度）
     * 比这个区间本身还大，报一个数会让人以为它准。
     */
    private const val SEC_PER_ENTRY_LO = 0.10
    private const val SEC_PER_ENTRY_HI = 1.00

    /**
     * 低于这个条数**不提示**（用户拍板里的"简短"就落在这里）。
     *
     * 为什么是 200：那一档的耗时上界约 1 分钟，用户对"按下去等一会儿"
     * 有合理预期；低于它的库（README 设计的 10~100 条规模）提示只会变成噪音 ——
     * 而"每次建库都弹一句"的后果是用户从此**闭眼点确定**，
     * 等真有一条贵的提示出现时它也一起被无视了。
     */
    const val WARN_ENTRIES = 200

    /**
     * 单条文本的块数上限默认值 —— **与 [RagIndexStore.ChunkParams.maxChunks] 同值**。
     *
     * ⚠ 为什么这里抄一个数而不是直接读它：本对象是**纯逻辑**（不碰 Android、
     *   不碰文件），而 `RagIndexStore` 依赖 `android.content.Context` ——
     *   直接引用它会让本文件的单测必须编进整个 Android 栈（现有那几个纯逻辑
     *   测试套件都是这么编不过的）。所以这里留一个默认值，
     *   而**真实调用点**（`EngineActivity`）显式把 ChunkParams 传进来。
     *   `tools/rag_cost/check_rag_cost_wiring.py` 正面钉住两个数相等 ——
     *   抄一份而没人比对，才是真的危险。
     */
    const val DEFAULT_MAX_CHUNKS = 16384

    /** 估算这一批要花多少秒（下界, 上界）。`count <= 0` 返回 (0.0, 0.0)。 */
    fun estimateSeconds(count: Int): Pair<Double, Double> {
        if (count <= 0) return 0.0 to 0.0
        return count * SEC_PER_ENTRY_LO to count * SEC_PER_ENTRY_HI
    }

    /** 把秒数量级说成**人话**（"约 10 秒" / "约 2 分钟" / "几分钟以上"）。 */
    fun humanSeconds(lo: Double, hi: Double): String {
        if (hi <= 0.0) return "几乎立刻"
        // 上界不给精确值：它本来就是"最坏情况"，精确到秒是假精确。
        return when {
            hi < 60.0 -> "最多约 ${ceil(hi)} 秒"
            hi < 600.0 -> "约 ${ceil(lo / 60.0).coerceAtLeast(1)}~${ceil(hi / 60.0)} 分钟"
            // ⚠ 小时这一档**必须显式存在**：旧口径下（上界 0.30 秒/条）
            //    7000 条算出来是 35 分钟，落进下面那档"十几分钟"里，
            //    看着像"等一下就好"。真机是**两小时**。
            //    一个会说"小时"的估算，是用户决定"现在建还是睡前挂着建"的唯一依据。
            hi < 3600.0 -> "约 ${ceil(lo / 60.0).coerceAtLeast(1)}~${ceil(hi / 60.0)} 分钟（可能超过半小时）"
            else -> "**数小时级**（约 ${ceil(lo / 3600.0).coerceAtLeast(1)}~${ceil(hi / 3600.0)} 小时）" +
                "，建议先只导一部分，或分批建"
        }
    }

    private fun ceil(v: Double): Int = kotlin.math.ceil(v).toInt()

    /**
     * 条数够大时返回一句**给用户看的确认文案**；否则 `null`（= 不必打扰）。
     *
     * 文案刻意保持三句以内，且**只说两件事**：要等多久、现在能做什么。
     * 不说"建议拆分"这类空话 —— README 里区分"追加"与"重建"正是为了这个，
     * 用户要拆自然会去用「追加」。
     *
     * [maxChunks] 一起传进来是为了在**撞上限**时把那件事提前说清：
     * 这时"再等也等不到后半段"，提示必须与"只是慢"分开（否则用户等完发现
     * 内容还是不全，而提示刚刚才说过"耐心等"）。
     */
    fun buildPrompt(count: Int, maxChunks: Int = DEFAULT_MAX_CHUNKS): String? {
        if (count < WARN_ENTRIES) return null
        val (lo, hi) = estimateSeconds(count)
        val sb = StringBuilder()
        sb.append("这一批 $count 条，逐条编码，${humanSeconds(lo, hi)}（条数越多越慢，与库大小成正比）。")
        if (count > maxChunks) {
            // ⚠ 两个上限管的是**不同的东西**，必须分开说，否则用户会以为
            //    "拆成两次建"能绕过它：maxChunks 是**单条文本**的块数上限
            //    （一条超长文本切不出更多块），与"库里有几条"无关。
            sb.append("\n注意：单条文本最多切 $maxChunks 块，超出的部分不会进索引。")
        }
        sb.append("\n期间这一屏不能操作，建议等完再动。开始？")
        return sb.toString()
    }

    /**
     * 建库**进行中**那一行状态文案（含"还要多久"的量级）。
     *
     * 为什么要在这里也报一次：确认框用户可能没细看，而"等的时候没有进度"
     * 是焦虑的真正来源 —— 一句量级能让他知道该不该去干别的。
     */
    fun buildingLine(count: Int): String {
        val (lo, hi) = estimateSeconds(count)
        return "建索引中…（$count 条，${humanSeconds(lo, hi)}）"
    }
}
