#!/usr/bin/env python3
"""从 **真实源码** 里各抽一份 `chunk` 实现，拼成两个可独立编译/运行的探针。

═══════════════════════════════════════════════════════════════════════════
为什么要"抽真源码"而不是在测试里抄一份控制流
═══════════════════════════════════════════════════════════════════════════
分块在两处各写一遍（C++ `chunk_text` / Kotlin `LlmEngine.chunk`），而两边
**各自的单测都绿**——验不了"两边一致"。抄一份进测试更不行：抄的那份会随
真源码漂移，那时测的是一份没人看的旧代码（本仓库反复记录的那类假绿）。

所以这里从**真实文件**里抽（LlmEngine 的 `chunk` + `pickChunkCut` +
`alignUtf8` + `nextUtf8Start`，TextBoundary 的 `SOFT_CUT_SEPS` + `pickCut` +
`boundaryBefore/After`），配上最小桩，做成一个可跑的程序：
  · Kotlin 侧：抽进 /tmp 的 .kt 里编译（用 CI 已有的 kotlinc）；
  · C++ 侧：直接 include `rag_index.h`（同一份被 native 编进去的头）。

两侧喂**同一份语料**、比**逐字节输出**。抽不到就报错退出（不能静默跳过）——
"抽不到"本身是判据：函数改名/拆走 = 守卫红。

⚠ 表与切点选择**不在 LlmEngine 里**：它们是 `TextBoundary` 的共享原语
（导入超长正文的切段是第二个消费方）。所以 kt 模式要**两个**源码文件；
只给一个的话"共享原语被谁换掉了"这件事在多份实现之间会看不见。

用法：extract_chunk.py kt  <LlmEngine.kt> <TextBoundary.kt> <out.kt>
      extract_chunk.py cpp <rag_index.h>   <out.cpp>
"""
import os
import re
import sys


def fn_body(src, name):
    """按真括号配对抽 `fun name(...)` / `inline ... name(...)` 的函数体。"""
    m = re.search(r'\bfun\s+' + re.escape(name) + r'\s*\(', src)
    if not m:
        return None
    i = src.index('{', m.end() - 1)
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '{':
            depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0:
                return src[m.start():j + 1]
    return None


def kt_probe(llm_engine, text_boundary):
    parts = {}
    # ① LlmEngine：建库那一路（`pickChunkCut` 只是**转发**，见 ②）
    for n in ('chunk', 'pickChunkCut', 'alignUtf8', 'nextUtf8Start'):
        b = fn_body(llm_engine, n)
        if b is None:
            sys.stderr.write('抽不到 Kotlin 的 %s（改名/拆走了？）\n' % n)
            return None
        parts[n] = b
    # ② TextBoundary：共享原语（表 + 切点选择 + 字符边界）。
    #    ⚠ 这几段**必须从这一份源码抽**，不能从 LlmEngine 抄 —— 它们在两处之间
    #    只有一份实体，而差分测试要比的正是"建库与导入切得一样不一样"。
    m = re.search(r'val\s+SOFT_CUT_SEPS[^\n]*=\s*listOf\([\s\S]*?\n\s*\)', text_boundary)
    if not m:
        sys.stderr.write('抽不到 Kotlin 的 SOFT_CUT_SEPS（在 TextBoundary 里）\n')
        return None
    seps = m.group(0)
    for n in ('pickCut', 'boundaryBefore', 'boundaryAfter'):
        b = fn_body(text_boundary, n)
        if b is None:
            sys.stderr.write('抽不到 TextBoundary 的 %s（切分原语被拆了？）\n' % n)
            return None
        parts[n] = b
    # 最长分隔符宽度：真源码里是一个 `private val`（C++ 侧当已知量传）。
    # 抽不到就用默认值 2（`\n\n`）—— 但**必须报出来**，不能让"宽度算错"
    # 变成一条静默的假绿（宽度变了、切点就变，而两边会一起变错）。
    w = 2
    mw = re.search(r'fun\s+maxSepWidth\s*\(\)\s*:\s*Int\s*\{([\s\S]*?)\n\s*\}', text_boundary)
    if mw and 'SOFT_CUT_SEPS' in mw.group(1):
        w = max(len(r0.replace('\\n', '\n').replace('\\t', '\t'))
                for r0 in re.findall(r'"((?:[^"\\]|\\.)*)"\s*to\s*(?:true|false)', seps))
    parts['__sepmax__'] = w

    out = []
    out.append('// AUTO-GENERATED by tools/rag_index/chunk_rule/extract_chunk.py — 不要手改。\n')
    out.append('package probe\n')
    out.append('// 最小桩：只为让抽出来的 chunk() 编得过（它原本用 RagIndexStore.Entry）。\n')
    out.append('object RagIndexStore {\n')
    out.append('    data class ChunkParams(val targetChars: Int = 480, val overlapChars: Int = 64,\n')
    # ⚠ 这个桩里的 maxChunks 必须与真实 `ChunkParams` 同值：差分测试比的是
    #   **分块行为**，而上限参与循环条件 —— 值不一致时两边会在"块数撞上限"
    #   的语料上分叉，那会变成一条假红（真源码其实是对的）。
    #   语料里没有撞上限的形态，所以这里只要求"不因默认值不同而分家"。
    out.append('                           val maxChunks: Int = 16384, val chunkRuleVersion: Int = 2)\n')
    out.append('    class Entry(val text: String, val source: String)\n')
    out.append('}\n')
    out.append('object Rules {\n')
    out.append(seps + '\n')
    # 最长分隔符宽度：真源码里由 `TextBoundary.maxSepWidth()` 给出，而这里
    # 直接从抽到的表算 —— 与真源码同一口径（那边也是扫这张表）。
    out.append('    val kSepMaxWidth: Int = %d\n' % parts['__sepmax__'])
    for n in ('chunk', 'pickChunkCut', 'alignUtf8', 'nextUtf8Start',
              'pickCut', 'boundaryBefore', 'boundaryAfter'):
        body = parts[n].replace('private ', '')
        # 抽出来的几段现在同住在 `Rules` 里：真源码里的 `TextBoundary.xxx`
        # 在这个探针里就是 `Rules.xxx`。不换的话探针编不过 —— 而"编不过"
        # 正是这里该有的反应（它证明这段代码真的来自共享原语，不是抄的）。
        body = body.replace('TextBoundary.', 'Rules.')
        # ⚠ `kSepMaxWidth` 是 LlmEngine 的私有常量（它才是"建库那一路的窗口回看
        #   距离"）。搬进 Rules 后要认这个名字 —— 否则转发那一行会变成
        #   `Rules.pickCut(text, pos, end, kSepMaxWidth)` 而 kSepMaxWidth
        #   不在作用域里：探针**编不过**，差分测试以"编译失败"收场。
        #   这个名字必须搬，不能改成别的常量：它决定窗口回看距离，
        #   而"回看距离"直接决定切点 —— 换个值就是换一套规则。
        body = body.replace('kSepMaxWidth', 'Rules.kSepMaxWidth')
        out.append(body + '\n')
    out.append('}\n')
    out.append(r'''
fun ktEsc(s: String): String {
    val o = StringBuilder()
    for (c in s) {
        when (c) {
            '\\' -> o.append("\\\\")
            '\n' -> o.append("<LF>")
            '\t' -> o.append("<TB>")
            else -> if (c.code < 0x20) o.append("<sp>") else o.append(c)
        }
    }
    return o.toString()
}

// 读 stdin 的语料（每行 "target \t overlap \t len \t <转义正文>"），
// 打 "块数|硬截数|[块]..."，与 C++ 侧逐字节比对。
fun main() {
    for (line in generateSequence(::readLine)) {
        if (line.isEmpty()) continue
        // 5 列：byteTarget \t byteOverlap \t charTarget \t charOverlap \t 正文。
        // Kotlin 的 targetChars 按**字符**算 —— 取 char 那两列（C++ 取 byte 那两列）。
        // 在"所有字符等长"的语料上两边窗口覆盖同样多的字符，边界才可比。
        val p = line.split('\t')
        val tg = p[2].toInt()
        val ov = p[3].toInt()
        val text = p[4].replace("\\n", "\n")
        val hc = IntArray(1)
        val v = Rules.chunk(text, RagIndexStore.ChunkParams(tg, ov), hc)
        val sb = StringBuilder()
        sb.append(v.size).append('|').append(hc[0]).append('|')
        if (System.getenv("CHUNK_MODE") == "chars") {
            // CJK 上比「每块的字符数」：语料的所有字符等长、且 target 已按字符换算，
            // 于是两边窗口覆盖同样多的字符 —— 这条比对**发现的**就是规则分家
            // （表不同 / 降级次序不同 / 硬截判定不同），不是单位差。
            for (e in v) sb.append(e.text.length).append(',')
        } else {
            for (e in v) sb.append('[').append(ktEsc(e.text)).append(']')
        }
        println(sb)
    }
}
''')
    return ''.join(out)


def cpp_probe():
    return r'''// AUTO-GENERATED by tools/rag_index/chunk_rule/extract_chunk.py — 不要手改。
// 直接复用被 native 编进去的那份头，不抄实现。
#include "rag_index.h"
#include <cstdio>
#include <cstdlib>
#include <iostream>
#include <string>
#include <vector>
using namespace ragindex;

static void put(const std::string & s) {
    std::string o;
    for (unsigned char c : s) {
        if (c == '\\') o += "\\\\";
        else if (c == '\n') o += "<LF>";
        else if (c == '\t') o += "<TB>";
        else if (c < 0x20) o += "<sp>";
        else o += (char) c;
    }
    printf("[%s]", o.c_str());
}

int main() {
    std::string line;
    while (std::getline(std::cin, line)) {
        if (line.empty()) continue;
        // 5 列：byteTarget \t byteOverlap \t charTarget \t charOverlap \t 正文。
        // C++ 的 targetChars 按**字节**算 —— 取 byte 那两列（Kotlin 取 char 那两列）。
        size_t a = line.find('\t');
        size_t b = line.find('\t', a + 1);
        size_t c = line.find('\t', b + 1);
        size_t d = line.find('\t', c + 1);
        int tg = std::stoi(line.substr(0, a));
        int ov = std::stoi(line.substr(a + 1, b - a - 1));
        std::string body = line.substr(d + 1);
        std::string text;
        for (size_t i = 0; i < body.size(); i++) {
            if (body[i] == '\\' && i + 1 < body.size() && body[i + 1] == 'n') { text += '\n'; i++; }
            else text += body[i];
        }
        ChunkCfg cfg; cfg.targetChars = tg; cfg.overlapChars = ov;
        int hc = 0;
        std::vector<std::string> v = chunk_text(text, cfg, &hc);
        printf("%d|%d|", (int) v.size(), hc);
        if (getenv("CHUNK_MODE") && std::string(getenv("CHUNK_MODE")) == "chars") {
            for (const auto & p : v) {
                int cp = 0;
                for (unsigned char ch : p) if ((ch & 0xC0) != 0x80) cp++;
                printf("%d,", cp);
            }
        } else {
            for (const auto & p : v) put(p);
        }
        printf("\n");
    }
    return 0;
}
'''


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else ''
    # kt 要两个源文件（LlmEngine + TextBoundary），cpp 只要一个
    if mode == 'kt':
        if len(sys.argv) != 5:
            sys.stderr.write(__doc__)
            return 2
        engine = open(sys.argv[2], encoding='utf-8').read()
        boundary = open(sys.argv[3], encoding='utf-8').read()
        out_path = sys.argv[4]
        text = kt_probe(engine, boundary)
    else:
        if len(sys.argv) != 4:
            sys.stderr.write(__doc__)
            return 2
        out_path = sys.argv[3]
        text = cpp_probe()
    if text is None:
        return 1
    open(out_path, 'w', encoding='utf-8').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
